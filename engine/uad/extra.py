"""The data an appraiser must supply that never prints on the report.

A-1 marks about 450 required or conditionally required rows "Does Not
Display".  Most of them the software fills in itself:

* structure and identity -- xlink labels, versions, ordinal numbers, the PDF
  reference and the software vendor (``delivery.py``);
* the facts about each photograph -- category, file, MIME type, date,
  altitude and position -- read from the file or from where it was placed;
* discriminators -- the Type a container carries so a reader knows which
  instance it is -- written by ``edit.write`` with the field they qualify.

What is left is appraiser input with nowhere on the page to type it: the scope
of work, the subject's and each comparable's coordinates, whether a
reconsideration of value was requested, how the cost to repair is expressed,
and so on.  This module lists those rows from A-1 (nothing here is a hand-typed
list of fields), reads their current values, and writes them back in schema
order.
"""
from __future__ import annotations

import json
import re
from copy import deepcopy
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Any

from lxml import etree

from . import bind, edit, schema
from .report import comparables

SPEC = Path(__file__).resolve().parents[1] / "spec"
M = f"{{{bind.MISMO}}}"

# generated by the software, never typed (see the module docstring)
GENERATED = re.compile(
    r"xlink|MISMOReferenceModel|AboutVersion|DocumentType|DocumentForm|MIMEType|ObjectURL"
    r"|^Image|AltitudeElevation|PropertyOrdinalNumber|PartyRoleType|ValuationUseType"
    r"|SequenceNumber|ValuationSoftware|ValuationAnalysisCategoryType|AgencyAppraiserIdentifierType"
    r"|ComparableAdjustmentType|ImprovementComponentType|EncumbranceType|UnitIdentifier$"
    r"|AdditionalValuationIdentifier$|ImprovementType$|ValuationReportContentIdentifier")

ROLES = {"Subject Property": "SubjectProperty", "Sales Comparable": "SalesComparable",
         "Rental Comparable": "RentalComparable", "Land Comparable": "LandComparable",
         "Gross Rent Multiplier Comparable": "GrossRentMultiplierComparable",
         "Property Analyzed Not Used": "PropertyAnalyzedNotUsed"}
KIND_OF_ROLE = {"SalesComparable": "sales", "RentalComparable": "rental",
                "GrossRentMultiplierComparable": "grm"}


@dataclass
class Row:
    uid: str
    context: str
    name: str
    segments: list[str]          # container path below the scope element
    scope: str                   # "valuation" or a ValuationUseType
    conditionality: str
    details: str
    format: str
    format_details: str
    definition: str
    options: list[dict] = field(default_factory=list)

    @property
    def label(self) -> str:
        words = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", self.name)
        return re.sub(r"\b(Indicator|Identifier|Type)$", "", words).strip()

    def to_json(self) -> dict[str, Any]:
        out = {k: v for k, v in self.__dict__.items() if k != "segments"}
        out["label"] = self.label
        out["container"] = "/".join(self.segments)
        return out


@lru_cache(maxsize=1)
def _identifying() -> frozenset[str]:
    """Types that say which instance a container is (A-1 discriminators).

    ``edit.write`` sets them with the field they qualify; changing one here
    would detach that field from the instance the report reads it from.
    """
    names = set()
    for marks in bind.discriminators().values():
        names.update(k for k in marks if not k.startswith("__") and k.endswith("Type"))
    return frozenset(names)


def _key(row: dict, start: str) -> str:
    return next(k for k in row if k.startswith(start))


@lru_cache(maxsize=1)
def rows() -> list[Row]:
    data = json.loads((SPEC / "delivery_spec.json").read_text(encoding="utf-8"))
    enums = _key(data[0], "Supported Data Point Enumerations")
    out: list[Row] = []
    seen: set[tuple] = set()
    for r in data:
        name = r["MISMO Data Point Name"]
        if not name or "Does Not Display" not in r["Report Location"]:
            continue
        if r["Conditionality"] not in ("R", "CR") or GENERATED.search(name):
            continue
        if name in _identifying():
            continue                                   # says which instance, set with it
        path = [s for s in r["MISMO xPath"].strip("/").split("/") if s and s != "MESSAGE"]
        if "IMAGE" in path:
            continue                                   # photo facts come from the file
        context = r["Additional Context"]
        role = next((v for k, v in ROLES.items() if context.startswith(k + ":")), "")
        if "PROPERTY" in path:
            if not role:
                continue
            below = path[path.index("PROPERTY") + 1:]
            scope = role
        elif "VALUATION_REPORT" in path:
            below = path[path.index("VALUATION_REPORT"):]
            scope = "valuation"
        else:
            continue
        if (scope, name, tuple(below)) in seen:
            continue
        seen.add((scope, name, tuple(below)))
        options = [{"value": v.strip(), "label": v.strip()}
                   for v in (r.get(enums) or "").split("|") if v.strip()]
        out.append(Row(r["Unique ID"], context, name, below, scope, r["Conditionality"],
                       (r["Conditionality Details"] or "").strip(),
                       (r["UAD Data Point Format Type"] or "").strip(),
                       (r["UAD Data Point Format Details"] or "").strip(),
                       (r["MISMO Data Point / Attribute Definition"] or "").strip(), options))
    return out


def by_uid(uid: str) -> Row:
    for r in rows():
        if r.uid == uid:
            return r
    raise KeyError(uid)


# ------------------------------------------------------------------ where
def _valuation(root) -> etree._Element | None:
    report = root.find(f".//{M}VALUATION_ANALYSIS")
    return report


def scopes(root, row: Row) -> list[tuple[str, etree._Element]]:
    """(label, element) for every place this row is answered."""
    if row.scope == "valuation":
        va = _valuation(root)
        return [("Report", va)] if va is not None else []
    props = [p for p in root.iter(f"{M}PROPERTY") if p.get("ValuationUseType") == row.scope]
    if row.scope in KIND_OF_ROLE:
        _sheet, role, _t = comparables.SHEETS[KIND_OF_ROLE[row.scope]]
        props = comparables.properties(root, role)
        return [(f"Comparable #{n}", p) for n, p in enumerate(props, start=1)]
    if row.scope == "SubjectProperty":
        return [("Subject", p) for p in props[:1]]
    return [(f"#{n}", p) for n, p in enumerate(props, start=1)]


def _repeats(segments: list[str]) -> bool:
    """Does the path pass through a container that repeats (IMPROVEMENT...)?"""
    for parent, child in zip(segments, segments[1:]):
        if bind.is_plural_of(parent, child):
            return True
    return False


def instances(base: etree._Element, row: Row) -> list[tuple[str, etree._Element | None]]:
    """The containers under a scope that hold this row's value.

    A path through a repeating container is answered once per instance that
    exists (a second dwelling is created where the dwelling is described, not
    here); a path that does not repeat is answered once and created on write.
    """
    if not _repeats(row.segments):
        found = base.find("/".join(f"{M}{s}" for s in row.segments))
        return [("", found)]
    found = base.findall("/".join(f"{M}{s}" for s in row.segments))
    return [(f"{row.segments[0].title().replace('_', ' ')} {n}" if len(found) > 1 else "", el)
            for n, el in enumerate(found, start=1)]


def read(root, row: Row) -> list[dict]:
    out = []
    for where, base in scopes(root, row):
        for which, container in instances(base, row):
            node = container.find(f"{M}{row.name}") if container is not None else None
            out.append({"scope": where, "instance": which,
                        "value": (node.text or "").strip() if node is not None else ""})
    return out


def _check(row: Row, value: str) -> str:
    v = value.strip()
    if not v:
        return ""
    fmt = row.format.lower()
    if fmt == "boolean" and v not in ("true", "false"):
        raise ValueError(f"{row.label} is Yes or No")
    if row.options and v not in {o["value"] for o in row.options}:
        raise ValueError(f"{v!r} is not one of the values A-1 allows for {row.name}")
    if fmt == "numeric":
        m = re.match(r"[+±±]?(\d+)\.(\d+)", row.format_details.replace("�", "±"))
        if not re.fullmatch(r"-?\d+(\.\d+)?", v):
            raise ValueError(f"{row.label} must be a number")
        if m and "." in v and len(v.split(".")[1]) > int(m.group(2)):
            raise ValueError(f"{row.label} allows {m.group(2)} decimal place(s)")
    length = re.match(r"(\d+)", row.format_details or "")
    if fmt == "string" and length and len(v) > int(length.group(1)):
        raise ValueError(f"{row.label} is at most {length.group(1)} characters")
    return v


def write(tree, row: Row, value: str, *, scope: int = 0, instance: int = 0):
    """Set the value in a copy of the document; return the copy if it is valid."""
    candidate = deepcopy(tree)
    root = candidate.getroot()
    v = _check(row, value)
    places = scopes(root, row)
    if not 0 <= scope < len(places):
        raise ValueError("there is no such property in this report")
    base = places[scope][1]
    found = instances(base, row)
    if not 0 <= instance < len(found):
        raise ValueError("there is no such instance in this report")
    container = found[instance][1]
    if container is None:
        if not v:
            return candidate
        container, _ = edit.ensure_path(base, list(row.segments))
    node = container.find(f"{M}{row.name}")
    if not v:
        if node is not None:
            container.remove(node)
    else:
        if node is None:
            node = edit.insert_ordered(container, row.name)
        node.text = v
    problems = schema.validate(candidate)
    if problems:
        raise ValueError("the document would not validate: " + problems[0].message)
    return candidate


def groups(root) -> list[dict]:
    """What the editor shows, grouped as A-1's Additional Context groups it."""
    out: dict[str, dict] = {}
    for row in rows():
        places = read(root, row)
        if not places:
            continue
        title = row.context.split(":")[0] if row.scope != "valuation" else "Scope of work and report"
        group = out.setdefault(title, {"title": title, "rows": []})
        group["rows"].append({**row.to_json(), "answers": places})
    order = ["Scope of work and report", "Subject Property", "Sales Comparable",
             "Rental Comparable", "Gross Rent Multiplier Comparable", "Land Comparable",
             "Property Analyzed Not Used"]
    return sorted(out.values(), key=lambda g: order.index(g["title"]) if g["title"] in order else 99)
