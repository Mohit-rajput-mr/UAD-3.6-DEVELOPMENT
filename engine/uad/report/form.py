    body = "".join(out)
    return "\n".join([
        kerned_fonts.css(),
        body,
        "body{font-family:'UAD 9'," + fonts.FALLBACK + ";font-kerning:normal;"
        "font-feature-settings:'kern' 1,'liga' 1;text-rendering:geometricPrecision}",
    ])


