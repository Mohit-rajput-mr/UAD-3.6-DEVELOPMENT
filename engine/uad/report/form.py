@dataclass
class Ctx:
    root: etree._Element
    scope: etree._Element | None = None
    folder: Path | None = None
    media: list[dict] = field(default_factory=list)
    placeholders: dict[str, str] = field(default_factory=dict)
    # Filling the form in is not the same as printing it: the report prints
    # only what has been answered, but an appraiser cannot answer a line that
    # is not on the page, so in edit mode an empty row keeps its place.
    edit: bool = False
    # empty exhibit boxes the appraiser has added (editor only)
    slots: list[dict] = field(default_factory=list)
    # Report Field IDs a file brought in, so the editor can show at a glance
    # what an import actually filled.  Reading a value back does not say where
    # it came from -- a field the appraiser typed and a field an import wrote
    # look identical -- so the import records what it answered and the report
    # marks exactly those.
    imported: frozenset[str] = frozenset()

    def inside(self, scope: etree._Element | None, **names: str) -> "Ctx":
        return Ctx(self.root, scope, self.folder, self.media,
                   {**self.placeholders, **names}, self.edit, self.slots,
                   self.imported)


@lru_cache(maxsize=1)
def _by_section_label() -> dict[tuple[str, str], list[str]]:
    out: dict[tuple[str, str], list[str]] = {}
    for fid, entry in _fields().items():
        head = fid.split(".")[0]
        for loc in entry.get("locations") or []:
            out.setdefault((head, loc.get("label", "").casefold()), []).append(fid)
    return out


def resolve(ids: list[str], label: str) -> list[str]:
    """C-1 IDs that A-1 files under another number are found by their label.

    C-1 v1.3 prints a few IDs A-1 does not carry (1.002 for the Final Value
    Condition Statement, which A-1 files under 26.013); the same label in the
    same section names the same data point.
    """
    out = []
    for fid in ids:
        if fid in _fields() and _fields()[fid].get("data_points"):
            out.append(fid)
            continue
        if "-" in fid:
            # an update / completion report's own ID: its appendix is the only
            # place to look it up, never the URAR's labels
            if binding(fid) is not None:
                out.append(fid)
            continue
        head = fid.split(".")[0]
        hits = _by_section_label().get((head, label.strip().casefold()), [])
        if not hits:
            hits = [k for (h, l), v in _by_section_label().items()
                    if l == label.strip().casefold() for k in v][:1]
        out += [h for h in hits if h not in out]
    return out


