def _walk(ctx: Ctx, fid: str):
    b = binding(fid)
    if b is None:
        return
    category = commentary_category(fid)
    comment = any(dp.get("mismo") in ("ValuationCommentText", "ValueMarketabilityImpactType")
                  and "VALUATION_COMMENTAR" in dp.get("xpath", "") for dp in b.data_points)
    owner = "Owner" in b.label and any((dp.get("requires") or {}).get("PartyRoleType") == "PropertyOwner"
                                       for dp in b.data_points)
    if owner:
        names = {dp.get("mismo") for dp in b.data_points
                 if (dp.get("requires") or {}).get("PartyRoleType") == "PropertyOwner"}
        for party in ctx.root.iter(f"{M}PARTY"):
            roles = [(r.text or "").strip() for r in party.iter(f"{M}PartyRoleType")]
            if "PropertyOwner" not in roles:
                continue
            for node in party.iter():
                if isinstance(node.tag, str) and _local(node) in names and (node.text or "").strip():
                    yield _local(node), node
        return
    roles = _fields().get(fid, {}).get("roles") or []
    if ctx.scope is None and roles and "Subject Property" not in roles and any(
            "PROPERTIES/PROPERTY" in dp.get("xpath", "") for dp in b.data_points):
        uses = {ROLE_USE.get(r, "") for r in roles}
        for prop in ctx.root.iter(f"{M}PROPERTY"):
            if prop.get("ValuationUseType") in uses:
                yield from bind._walk(ctx.root, b, prop, 1)
        return
    if repeats_as_list(fid):
        # One field, one value per repeated block (PROJECT_AMENITY each holds
        # one AmenityType): every block is read, not the first -- D-1 condo 2
        # prints all six of the project's amenities on this one row.
        principal = next(dp for dp in b.data_points if dp.get("mismo") == (printed_point(fid) or next(
            d["mismo"] for d in b.data_points if d.get("enumerations") and not d.get("attribute"))))
        container = bind.repeating_container(principal.get("xpath", ""))
        segs = bind._tail(principal.get("xpath", ""))
        base = ctx.scope if ctx.scope is not None else (
            bind.subject(ctx.root) if bind.PROPERTY_PATH in principal.get("xpath", "") else ctx.root)
        seen = set()
        for node in (base.iter(f"{M}{principal['mismo']}") if base is not None else []):
            if not bind._matches(node, segs):
                continue
            block = node.getparent()
            while block is not None and _local(block) != container:
                block = block.getparent()
            if block is None:
                continue
            path = bind.stable_path(block)
            if path in seen:
                continue
            seen.add(path)
            yield from bind._walk(ctx.root, b, block, 1)
        return
    for name, node in bind._walk(ctx.root, b, ctx.scope, 1):
        if comment and name in ("ValuationCommentText", "ValueMarketabilityImpactType"):
            if not category:
                continue
            got = node.getparent().findtext(f"{M}ValuationAnalysisCategoryType", "").strip()
            if got != category:
                continue
        yield name, node


def raw_values(ctx: Ctx, fid: str) -> list[str]:
    return [(n.text or "").strip() for _name, n in _walk(ctx, fid)
            if (n.text or "").strip()]


def instances(ctx: Ctx, fid: str) -> list[tuple[str, list[tuple[str, str]]]]:
    """Values grouped by the repeated container each sits in, in document order."""
    order: list[str] = []
    groups: dict[str, list[tuple[str, str]]] = {}
    for name, node in _walk(ctx, fid):
        text = (node.text or "").strip()
        if not text:
            continue
        key = bind.instance_of(node)
        if key not in groups:
            groups[key] = []
            order.append(key)
        text = bind.with_unit(text, node)
        if (name, text) not in groups[key]:
            groups[key].append((name, text))
    return [(k, groups[k]) for k in order]


AREA_UNITS = {"SquareFeet": "Sq. Ft.", "Acres": "Acres", "SquareMeters": "Sq. M.",
              "Hectares": "Hectares"}


def _area(text: str, unit: str) -> str:
    """An area as the samples print it: '14,950 Sq. Ft.', '10.5 Acres'."""
    try:
        number = float(text)
    except ValueError:
        return f"{text} {AREA_UNITS.get(unit, unit)}"
    shown = f"{number:,.3f}".rstrip("0").rstrip(".")
    return f"{shown} {AREA_UNITS.get(unit, bind._humanise(unit))}"


def shown(ctx: Ctx, fid: str) -> list[str]:
    """The printed text for a field: one entry per instance it holds."""
    return [text for text, _key in shown_pairs(ctx, fid)]


def shown_pairs(ctx: Ctx, fid: str) -> list[tuple[str, str]]:
    """(printed text, stable address of the repeated block it sits in) per
    instance -- so the editor writes each value back into its own block."""
    b = binding(fid)
    if b is None:
        return []
    out = []
    per = "Per " in (b.label or "")
    tree = ctx.root.getroottree()
    for key, group in instances(ctx, fid):
        text = bind.display_value(group, b)
        if text and not per:
            text = re.sub(r"(\$[\d,]+)\.00\b", r"\1", text)
        if text:
            stable = ""
            if key.startswith("/"):
                hit = tree.xpath(key)
                stable = bind.stable_path(hit[0]) if hit else ""
            out.append((text, stable))
    return out


