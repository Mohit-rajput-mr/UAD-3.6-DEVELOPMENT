def _relations(root: etree._Element) -> dict[str, etree._Element]:
    """DEFECT label -> the element its RELATIONSHIP says it belongs to."""
    labels = {el.get(f"{XLINK}label"): el for el in root.iter()
              if isinstance(el.tag, str) and el.get(f"{XLINK}label")}
    out = {}
    for rel in root.iter(f"{M}RELATIONSHIP"):
        arc = rel.get(f"{XLINK}arcrole", "")
        if "DEFECT_ContainsDefectOf_" in arc:
            target = labels.get(rel.get(f"{XLINK}to"))
            if target is not None:
                out[rel.get(f"{XLINK}from")] = target
    return out


def _defect_targets(ctx: Ctx, key: str) -> list:
    """What the DEFECT a table row reads is a defect of, by its
    DEFECT_ContainsDefectOf_* arc: the amenities table's Feature is the
    AMENITY's type (D-1 Condo1 "Balcony"), not a value of the defect."""
    if not key.startswith("/"):
        return []
    hit = ctx.root.getroottree().xpath(key)
    el = hit[0] if hit else None
    while el is not None and _local(el) != "DEFECT":
        el = el.getparent()
    label = el.get(f"{XLINK}label") if el is not None else None
    if not label:
        return []
    want = {r.get(f"{XLINK}to") for r in ctx.root.iter(f"{M}RELATIONSHIP")
            if r.get(f"{XLINK}from") == label and "DEFECT_ContainsDefectOf_" in (r.get(f"{XLINK}arcrole") or "")}
    return [e for e in ctx.root.iter() if isinstance(e.tag, str) and e.get(f"{XLINK}label") in want]


def _within(ctx: Ctx, key: str, targets: list) -> bool:
    if not key.startswith("/"):
        return False
    hit = ctx.root.getroottree().xpath(key)
    return bool(hit) and any(hit[0] is t or t in hit[0].iterancestors() for t in targets)


def _no_defects(ctx: Ctx, el: dict) -> bool:
    """B-1: a section's DDD shows "None" when its DefectsExistIndicator is
    false -- and the Summary's, which gathers six of them, only "when all
    indicators are false" (B-1 p82).  Reading only the first (Site's) printed
    "None" for Condo1, whose unit interior has defects needing no action; it
    prints "There are no apparent defects ... requiring action" instead."""
    scope = ctx.scope if ctx.scope is not None else subject(ctx)
    names: list[str] = []
    for row in el["rows"]:
        for c in row["cells"]:
            for fid in c["ids"]:
                for dp in field_entry(fid).get("data_points", []):
                    # its condition, or one named in A-1's own IF (1.056's
                    # "... AND OutbuildingDefectsExistIndicator = true")
                    stated = re.findall(r"\w+DefectsExistIndicator", dp.get("conditionality_details") or "")
                    for k in list(dp.get("requires") or {}) + stated:
                        if k.endswith("DefectsExistIndicator") and k not in names:
                            names.append(k)
    answers = [(n.text or "").strip() for k in names
               for n in (scope.iter(f"{M}{k}") if scope is not None else [])]
    return bool(answers) and all(a == "false" for a in answers)


def _td(t: str) -> str:
    cls = " class='num'" if re.match(r"^-?\$[\d,]", t or "") else ""
    return f"<td{cls}><span>{t}</span></td>"


# 'IF (AmenityType = "IngroundPool" OR "IngroundSpa" OR "Sauna") AND Exists':
# A-1 writes a choice of several values as one condition, which does not
# reduce to the single key/value pair ``requires`` holds, so it is read here.
CONDITION = re.compile(r'(\w+)\s*=\s*"([^"]+)"((?:\s*OR\s*"[^"]+")*)')
OR_VALUE = re.compile(r'"([^"]+)"')


@lru_cache(maxsize=4096)
def _condition_values(details: str) -> tuple[tuple[str, frozenset[str]], ...]:
    out: dict[str, set[str]] = {}
    for key, first, rest in CONDITION.findall(details or ""):
        out.setdefault(key, set()).update([first] + OR_VALUE.findall(rest))
    return tuple((k, frozenset(v)) for k, v in out.items())


def _instance_ok(dp: dict, instance: "etree._Element | None") -> bool:
    """Does the row's instance meet the condition A-1 puts on this data point
    (``requires``: ImprovementComponentType = WallsAndCeiling ...)?"""
    if instance is None:
        return True
    wanted: dict[str, frozenset[str]] = {
        k: frozenset([v]) for k, v in (dp.get("requires") or {}).items()}
    for key, values in _condition_values(dp.get("conditionality_details") or ""):
        wanted.setdefault(key, values)
    for key, values in wanted.items():
        if key.startswith("@") or key.startswith("__"):
            continue
        node = instance.find(f".//{M}{key}")
        if node is None:
            holder = instance.getparent()
            while holder is not None and node is None:
                node = holder.find(f"{M}{key}")
                holder = holder.getparent()
        if node is not None and (node.text or "").strip() not in values:
            return False
    return True


def cell_point(fid: str, container: str, instance: "etree._Element | None" = None) -> dict:
    """Which of a field's data points a table row writes.

    One Report Field ID can name several data points in different containers
    -- "Proximity" is an environmental condition's, a body of water's or a
    site influence's -- and the row's own container decides which.
    """
    b = binding(fid)
    if b is None:
        return {}
    points = ([dp for dp in b.data_points if dp.get("mismo") and not dp.get("attribute")]
              # a measure carried with its unit (12.013 "Total Area" @AreaUnitOfMeasureType)
              or [dp for dp in b.data_points if dp.get("mismo")])
    if container:
        inside = [dp for dp in points
                  if container in [s for s in dp.get("xpath", "").strip("/").split("/") if s]]
        if inside:
            points = inside
    if instance is not None:
        # the row's own tag first (CEILING_HEIGHT), then the conditions it meets
        tag = etree.QName(instance).localname
        own = [dp for dp in points if tag in dp.get("xpath", "")]
        if own:
            points = own
        meets = [dp for dp in points if _instance_ok(dp, instance)]
        if meets:
            points = meets
    # "Monthly Payment" is the amount; its PaymentAmountAvailableIndicator
    # says whether there is one, and follows from what is typed
    valued = [dp for dp in points if not dp["mismo"].endswith("AvailableIndicator")]
    if valued and len(valued) < len(points):
        points = valued
    enumerated = [dp for dp in points if (dp.get("format_type") or "") == "Enumerated"]
    return (enumerated or points or [{}])[0]


def point_choices(dp: dict) -> tuple[tuple[str, str], ...]:
    return tuple(((o.get("value") or "").strip(),
                  bind.answer_label((o.get("value") or "").strip(), o.get("display") or o.get("value") or ""))
                 for o in dp.get("enumerations") or [] if (o.get("value") or "").strip()
                 and not dp.get("attribute"))


def _instance_el(ctx: "Ctx", key: str):
    if not key:
        return None
    hits = ctx.root.getroottree().xpath(key)
    return hits[0] if hits else None


def _container_of(ctx: "Ctx", key: str, sel: str, fid: str) -> str:
    if key:
        hits = ctx.root.getroottree().xpath(key)
        if hits:
            # the row may be keyed on a repeat nested below the field's own
            # container (CEILING_HEIGHT inside INTERIOR_COMPONENT): use the
            # nearest one the field's data points actually pass through
            b = binding(fid)
            tags = {t for dp in (b.data_points if b else [])
                    for t in dp.get("xpath", "").strip("/").split("/") if t}
            node = hits[0]
            while node is not None and etree.QName(node).localname not in tags:
                node = node.getparent()
            return etree.QName(node if node is not None else hits[0]).localname
    for f in (sel, fid):
        b = binding(f) if f else None
        for dp in (b.data_points if b else []):
            c = bind.repeating_container(dp.get("xpath", ""))
            if c:
                return c
    return ""


def _stable(ctx: "Ctx", key: str) -> str:
    """The instance key (a getpath) as a stable, tag-named address."""
    if not key:
        return ""
    hits = ctx.root.getroottree().xpath(key)
    return bind.stable_path(hits[0]) if hits else ""


@lru_cache(maxsize=4096)
def _repeats(fid: str) -> bool:
    """Does this field sit in a container A-1 lets repeat (a utility, a room)?"""
    b = binding(fid)
    return bool(b and any(bind.repeating_container(dp.get("xpath", "")) for dp in b.data_points
                          if dp.get("mismo") and not dp.get("attribute")))


def _cell(text: str, fid: str, ctx: "Ctx", *, key: str = "", sel: str = "",
          label: str = "", new: bool = False, cat: str = "", td_class: str = "",
          point: str = "") -> str:
    """A table cell in the editor: the value, typed or picked where it prints.

    The cell names the field and the instance it belongs to (``data-tk``, the
    path of the repeating container its value sits in).  A fixed row with no
    instance yet (Utilities: "Gas") names the field that identifies the row
    and the row's label, so the first value typed creates the instance with
    its type; the empty line under a repeating table creates a new one.
    """
    dp = cell_point(fid, _container_of(ctx, key, sel, fid), _instance_el(ctx, key))
    if point:
        # the cell names its own data point (Area: finished or unfinished)
        b_ = binding(fid)
        dp = next((d for d in (b_.data_points if b_ else []) if d.get("mismo") == point), dp)
    attrs = (f" data-tf='{esc(fid)}' data-tk='{esc(_stable(ctx, key))}'"
             f" data-tdp='{esc(dp.get('mismo', ''))}' data-k='{kind_of_point(dp)}'")
    if "VALUATION_COMMENTAR" in dp.get("xpath", "") and (commentary_category(fid) or cat):
        attrs += f" data-tcat='{esc(commentary_category(fid) or cat)}'"
    if sel:
        attrs += f" data-tsel='{esc(sel)}' data-tlab='{esc(label)}'"
    if new:
        attrs += " data-tnew='1'"
    if ctx.scope is not None:
        # a cost line is written into the cost block its arc ties to the
        # dwelling or outbuilding, as it is read (_walk, _arc_linked)
        target = (_arc_linked(ctx.scope, dp.get("xpath", "")) if _local(ctx.scope) == "IMPROVEMENT" else None)
        attrs += f" data-tscope='{esc(bind.stable_path(target if target is not None else ctx.scope))}'"
    if point_choices(dp):
        inner = f"<span class='v pick'{attrs} tabindex='0' role='button'>{text}</span>"
    else:
        inner = f"<span class='v'{attrs} contenteditable='true' spellcheck='false'>{text}</span>"
    if fid in NEGATIVE_FIDS and not point_choices(dp) and b1_value(fid, text or "") != (text or ""):
        # shown as printed; typed back it is stored positive (entry.POSITIVE_ONLY)
        inner = (f"<span class='v'{attrs} contenteditable='true' spellcheck='false'>"
                 f"{b1_value(fid, text)}</span>")
    if text and label_prefix(fid):
        # B-1's own words before the value print in the editor too, outside
        # what is typed ("Greatest Number of Units Owned - " 2)
        words = with_label_prefix(fid, "\x00").split("\x00")[0]
        inner = f"<span class='pre'>{esc(words)}</span>{inner}"
    classes = ([td_class] if td_class else []) + (
        ["num"] if re.match(r"^-?\$[\d,]", text or "") else [])
    cls = f" class='{' '.join(classes)}'" if classes else ""
    return f"<td{cls}>{inner}</td>"


