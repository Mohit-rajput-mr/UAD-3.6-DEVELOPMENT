PARTY_ROLE_ORDER = ("Client", "Lender", "ManagementCompany")


def _local(node: etree._Element) -> str:
    return etree.QName(node).localname


def _find_text(node: etree._Element, name: str) -> str:
    found = node.find(f".//{M}{name}")
    return (found.text or "").strip() if found is not None and found.text else ""


def _role_display(role: str) -> str:
    return {"ManagementCompany": "Appraisal Management Company"}.get(
        role, bind._humanise(role))


def contact_parties(ctx: Ctx) -> list[tuple[etree._Element, str]]:
    """The client, lender and AMC blocks (C-1 "[Role]/[Role]")."""
    out = []
    for party in ctx.root.iter(f"{M}PARTY"):
        roles = [(r.text or "").strip() for r in party.iter(f"{M}PartyRoleType")]
        wanted = [r for r in PARTY_ROLE_ORDER if r in roles]
        if not wanted:
            continue
        if "Client" in roles:
            # A-1 2.011: the client's second role is any of Attorney, Investor,
            # Lender, Appraisal Management Company or Other (its description)
            other = client_role(party)
            title = "Client" + (f"/{other[1]}" if other[1] else "")
        else:
            title = "/".join(_role_display(r) for r in wanted)
        out.append((party, title))
    return out


def client_role(party: etree._Element) -> tuple[etree._Element | None, str]:
    """The client party's second ROLE_DETAIL and what it prints."""
    for detail in party.iter(f"{M}ROLE_DETAIL"):
        kind = (detail.findtext(f"{M}PartyRoleType") or "").strip()
        if kind and kind != "Client":
            if kind == "Other":
                return detail, (detail.findtext(f"{M}PartyRoleTypeOtherDescription") or "").strip()
            return detail, _role_display(kind)
    return None, ""


def subject(ctx: Ctx) -> etree._Element | None:
    return bind.subject(ctx.root)


def improvements(ctx: Ctx, kind: str) -> list[etree._Element]:
    subj = subject(ctx)
    if subj is None:
        return []
    return [imp for imp in subj.iter(f"{M}IMPROVEMENT")
            if _find_text(imp, "ImprovementType") == kind]


def section_instances(ctx: Ctx, title: str) -> list[tuple[Ctx, str]]:
    """The copies a tab's section is drawn in, each with its printed title."""
    base = title.split(" - [")[0].strip()
    if base == "Dwelling Exterior":
        dwellings = improvements(ctx, "Dwelling")
        many = len(dwellings) > 1
        out = []
        for imp in dwellings:
            sid = _find_text(imp, "StructureIdentifier")
            name = f"Dwelling Exterior - {sid}" if (sid and many) else "Dwelling Exterior"
            out.append((ctx.inside(imp, structure=sid), name))
        return out or [(ctx, base)]
    if base == "Outbuilding":
        out = []
        for imp in improvements(ctx, "Outbuilding"):
            kind = _find_text(imp, "OutbuildingTypeOtherDescription") or \
                bind._humanise(_find_text(imp, "OutbuildingType"))
            out.append((ctx.inside(imp, outbuilding=kind),
                        f"Outbuilding - {kind}" if kind else "Outbuilding"))
        return out
    if base == "Unit Interior":
        subj = subject(ctx)
        units = list(subj.iter(f"{M}PROPERTY_UNIT")) if subj is not None else []
        many = len(units) > 1
        out = []
        for unit in units:
            imp = next((a for a in unit.iterancestors(f"{M}IMPROVEMENT")), None)
            parts = ["Unit Interior"]
            if imp is not None and _find_text(imp, "ImprovementType") == "Outbuilding":
                parts.append(bind._humanise(_find_text(imp, "OutbuildingType")))
            sid = _find_text(imp, "StructureIdentifier") if imp is not None else ""
            uid = _find_text(unit, "UnitIdentifier")
            if many and sid:
                parts.append(sid)
            if many and uid:
                parts.append(uid)
            out.append((ctx.inside(unit, structure=sid, unit=uid), " - ".join(parts)))
        return out or [(ctx, base)]
    return [(ctx, base)]


