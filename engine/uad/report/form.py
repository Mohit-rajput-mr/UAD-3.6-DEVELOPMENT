@dataclass
class Item:
    """One element in a column, already resolved against the case."""
    kind: str                 # row | head | check | prose | italic | photo | table
    style: str = ""
    label: str = ""
    values: list[str] = field(default_factory=list)
    checked: bool | None = None
    yes_no: bool = False
    level: int = 0
    html: str = ""
    visible: bool = False
    fids: list[str] = field(default_factory=list)
    keys: list[str] = field(default_factory=list)    # each value's repeated block


@dataclass
class Block:
    kind: str                 # tab | h1 | h2 | cols | table | prose | italic | check | exhibits | grid | lead | text
    section: str = ""
    title: str = ""
    html: str = ""
    left: list[Item] = field(default_factory=list)
    right: list[Item] = field(default_factory=list)
    visible: bool = False
    group: int = 0            # 0 content, 1 h2, 2 h1, 3 tab
    new_page: bool = False
    decoration: bool = False
    fids: list[str] = field(default_factory=list)


LEVEL = {"TXR-B": 0, "TX-B": 0, "TXR": 0, "TXR-I": 1, "TXR-II": 2, "CK1": 0, "CK-1I": 1}


def _label_fill(label: str, ctx: Ctx) -> str:
    """Resolve the bracketed placeholders C-1 prints in a label."""
    subs = {"[Structure Identifier]": ctx.placeholders.get("structure", ""),
            "[Unit Identifier]": ctx.placeholders.get("unit", ""),
            "[Outbuilding Type]": ctx.placeholders.get("outbuilding", "")}
    for k, v in subs.items():
        if k in label:
            label = label.replace(f" - {k}", f" - {v}" if v else "").replace(k, v)
    label = re.sub(r"\s*\(\s*\)", "", label)
    return " ".join(label.split())


def _column_item(el: dict, ctx: Ctx) -> Item:
    kind = el["kind"]
    label = _label_fill(el.get("text", ""), ctx)
    ids = resolve(el.get("ids", []), el.get("text", ""))
    style = el.get("style", "")
    if kind == "row":
        if not ids:
            return Item("head", style=style, label=label, level=LEVEL.get(style, 0))
        pairs = shown_pairs(ctx, ids[0]) if len(ids) == 1 else []
        values = [t for t, _k in pairs] if len(ids) == 1 else [text_of(ctx, ids)] if text_of(ctx, ids) else []
        if label.startswith("Total Estimated Cost of Items") and cost_to_repair_type(ctx) != "TotalCost":
            values = []
        item = Item("row", style=style, label=label, values=values,
                    level=LEVEL.get(style, 0),
                    visible=bool(values) or ctx.edit, fids=ids)
        item.keys = [k for _t, k in pairs]
        return item
    if kind == "head":
        return Item("head", style=style, label=label, level=LEVEL.get(style, 0))
    if kind == "check":
        value = checkbox(ctx, ids[0], label) if ids else None
        return Item("check", style=style, label=label, checked=value,
                    yes_no=el.get("yes_no", False), level=LEVEL.get(style, 0),
                    visible=value is not None or (ctx.edit and bool(ids)),
                    fids=ids)
    if kind == "prose":
        value = text_of(ctx, ids, " ")
        return Item("prose", style="TXC-B1", label=label, values=[value] if value else [],
                    visible=bool(value) or (ctx.edit and bool(ids)), fids=ids)
    if kind == "italic":
        return Item("italic", style="TXC-I1", label=label, level=0)
    if kind == "photo":
        return Item("photo", fids=ids)
    return Item("head", label=label)


def build(tree, *, folder: Path | None = None, media: list[dict] | None = None,
          sample: bool = False, edit: bool = False,
          slots: list[dict] | None = None,
          imported: Iterable[str] | None = None) -> list[Block]:
    """Every block of the report for one case, in order, with visibility set."""
    root = tree.getroot() if hasattr(tree, "getroot") else tree
    ctx = Ctx(root, None, folder, list(media or []), edit=edit,
              slots=list(slots or []) if edit else [],
              imported=frozenset(imported or ()))
    elements: list[dict] = []
    for pg in form()["pages"]:
        for el in pg["elements"]:
            elements.append({**el, "page": pg["page"]})

    # split into sections at each tab; the Summary is everything before the first
    sections: list[tuple[str, list[dict]]] = [("Summary", [])]
    for el in elements:
        if el["kind"] == "tab":
            sections.append((el["title"], [el]))
            continue
        if el["page"] == 40 and sections[-1][0] == "Supplemental Information" and \
                not any(e.get("page") == 40 for e in sections[-1][1]):
            sections.append(("Certifications and Scope of Work", []))
        sections[-1][1].append(el)

    blocks: list[Block] = []
    for title, els in sections:
        base = title.split(" - [")[0]
        if section_shown(ctx, base) is False:
            continue
        for sctx, printed in section_instances(ctx, title):
            blocks += _section(title, printed, els, sctx, sample=sample)
    _resolve_visibility(blocks)
    return blocks


