@lru_cache(maxsize=1)
def image_categories() -> dict[str, tuple[str, str]]:
    """ImageCategoryType -> (section name, caption) from the A-1 enumerations.

    A category whose Report Location names a field gives its section and the
    caption the report prints.  The ``...Exhibit`` categories "do not display"
    a caption and belong to the section their name spells.
    """
    rows = json.loads((SPEC / "enumerations.json").read_text(encoding="utf-8"))
    out: dict[str, tuple[str, str]] = {}
    display_key = next((k for k in rows[0] if k.startswith("Output Report Display")), "")
    names = {re.sub(r"[^a-z]", "", n.lower()): n for _k, n in bind.SECTIONS}
    names["assignment"] = "Assignment Information"
    names["marketanalysis"] = "Market"
    names["project"] = "Project Information"
    names["supplemental"] = "Supplemental Information"
    names["subjectlisting"] = "Subject Listing Information"
    for r in rows:
        if r.get("MISMO Data Point / Attribute Name") != "ImageCategoryType":
            continue
        value = r.get("Supported Enumerations", "")
        caption = str(r.get(display_key, "")).split("\n")[0]
        if "Does Not Display" in caption:
            caption = ""
        loc = r.get("Report Location", "")
        section = ""
        m = re.search(r":\s*([^-]+?)\s+-", loc)
        if m:
            section = m.group(1).strip()
        elif value.endswith("Exhibit"):
            key = re.sub(r"[^a-z]", "", value[:-len("Exhibit")].lower())
            section = names.get(key, "")
        out.setdefault(value, (section, caption))
    return out


