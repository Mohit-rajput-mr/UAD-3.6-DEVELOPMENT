def _fixed_text(out: list[Block], printed: str, el: dict, ctx: Ctx) -> None:
    """One paragraph of the report's own fixed wording.

    The Certifications and Scope of Work pages are wording the GSEs set, not
    data: C-1 marks each paragraph with a slot in the margin whose field
    carries the display rule (``Always displays``, or a condition on the
    assignment), and the paragraph prints only when that rule says so.
    """
    text = " ".join(str(el.get("text", "")).split())
    if not text:
        return
    fid = ctx.placeholders.get("rule_fid", "")
    kinded = True       # every report's fixed wording flows as its Layout sets it
    number = ctx.placeholders.pop("pending_no", "") if kinded else ""
    if kinded:
        # C-2 / C-3 draw a paragraph line by line.  A line set within 15pt of
        # the one before (the leading is 12pt; paragraphs are 17-18pt apart)
        # and not opened by a number continues that paragraph, so the
        # wording flows as the official report sets it.
        if text.startswith("provided significant real property appraisal assistance") \
                and ctx.placeholders.get("contact_names"):
            text = f"{ctx.placeholders['contact_names']} {text}"
        y, page_no = float(el.get("y", 0)), str(el.get("page", ""))
        last_y = float(ctx.placeholders.get("last_y", "-99"))
        cont = (not number and ctx.placeholders.get("last_page") == page_no
                and 0 < y - last_y < 15)
        ctx.placeholders["last_y"], ctx.placeholders["last_page"] = str(y), page_no
        prev = out[-1] if out else None
        if cont and prev is not None and getattr(prev, "para_text", None) is not None:
            prev.para_text += " " + text
            prev.html = prev.html.rsplit("<span class='pt'>", 1)[0] + \
                f"<span class='pt'>{esc(prev.para_text)}</span></div>"
            return
        if "para" in ctx.placeholders:
            # B-2 / B-3 state the alternatives a slot governs as one sentence
            # each ("Display descriptive text when GovernmentAgencyAppraisalType
            # = 'FHA' ...", then "... 'USDA'", then "... 'VA'"), in the order
            # the Layout sets the paragraphs under it: the n-th paragraph after
            # the slot takes the n-th sentence.  A numbered certification
            # counts by its number instead.
            if ctx.placeholders.get("para_open") == "1":
                ctx.placeholders["para"] = str(int(ctx.placeholders["para"]) + 1)
            ctx.placeholders["para_open"] = "1"
            if ctx.placeholders.get("cert_no", "") == "":
                ctx.placeholders["alt"] = ctx.placeholders["para"]
                ctx.placeholders["alt_src"] = "para"
        shown = _anchor_gate(ctx, fid)
        if shown and not _agency_ok(ctx, text):
            shown = False
        lead = f"<b>{esc(number)}</b> " if number else ""
        blk = Block("static", section=printed, visible=shown, fids=[fid],
                    html=f"<div class='txc kp'>{lead}<span class='pt'>{esc(text)}</span></div>")
        blk.para_text = text
        out.append(blk)
        return
    shown = _anchor_gate(ctx, fid)
    if shown and not _agency_ok(ctx, text):
        shown = False
    numbered = bool(NUMBER.match(text))
    prev = out[-1] if out else None

    cls = "txc np" if numbered else "txc"
    out.append(Block("static", section=printed, visible=shown, fids=[fid],
                     html=f"<div class='{cls}'>{esc(text)}</div>"))


def _signature_html(ctx: Ctx, els: list[dict]) -> str:
    def first(pred) -> str:
        e = next((e for e in els if pred(e)), None)
        return (e.get("ids") or [""])[0] if e else ""
    role_f = first(lambda e: "[Role]" in (e.get("text") or ""))
    name_f = first(lambda e: "[Contact Name]" in (e.get("text") or ""))
    date_f = first(lambda e: e["kind"] == "slot" and (e.get("ids") or [""])[0]
                   and binding(e["ids"][0]) is not None
                   and any(dp.get("mismo") == "ExecutionDate" for dp in binding(e["ids"][0]).data_points))
    rows = [e for e in els if e["kind"] == "row" and e.get("ids")]
    roles = shown(ctx, role_f) if role_f else []
    names = shown(ctx, name_f) if name_f else []
    dates = shown(ctx, date_f) if date_f else []
    cols = {e["text"]: (e["ids"][0], shown(ctx, e["ids"][0])) for e in rows}

    def value(fid: str, text: str, n: int) -> str:
        # In the editor the appraiser's own date and licence are typed where
        # they print (the first signer: the appraiser).  The name is the
        # appraiser's contact name, entered under Assignment Information.
        if ctx.edit and n == 0 and fid:
            control = _value_control(ctx, fid, text)
            return control or (f"<span class='v' data-fid='{esc(fid)}' data-k='{input_kind(fid)}'"
                               f" contenteditable='true' spellcheck='false'>{esc(text)}</span>")
        return esc(text)
    out = []
    for n in range(max(len(roles), len(names), 1)):
        role = roles[n] if n < len(roles) else ""
        name = names[n] if n < len(names) else ""
        date = dates[n] if n < len(dates) else (dates[0] if dates and n == 0 else "")
        # the signer's own signature, kept with the case (category
        # "signature", caption "Signature <n>"), drawn above the line
        mine = [m for m in ctx.media if m.get("category") == "signature"
                and (m.get("caption") or "").strip() == f"Signature {n + 1}"]
        src = _data_uri(Path(mine[-1]["path"])) if mine else ""
        sig = f"<img class='sgimg' alt='Signature' src='{src}'>" if src else esc(name)
        if ctx.edit:
            sig += (f"<span class='sgsign{' has' if src else ''}' role='button' tabindex='0'"
                    f" data-signer='{n + 1}' data-media='{esc(mine[-1].get('media_id', '')) if mine else ''}'>"
                    f"{'Change signature' if src else '&#x270D; Sign here'}</span>")
        right = "".join(
            f"<div class='sgr'><span>{esc(label)}</span>"
            f"<span>{value(fid, v[n] if n < len(v) else '', n)}</span></div>"
            for label, (fid, v) in cols.items())
        out.append(
            "<div class='sg'><div class='sgl'>"
            f"<div class='sgrole'>{esc(_role_display(role) if role else '')}</div>"
            f"<div class='sgline'><span class='sgname'>{sig}</span><span class='sgdate'>{value(date_f, date, n)}</span></div>"
            f"<div class='sgcap'><span>{esc(name)}</span><span>Date of Signature and Report</span></div>"
            f"</div><div class='sgrt'>{right}</div></div>")
    return "".join(out)


def _party_item(el: dict, ctx: Ctx) -> Item:
    """A contact row read inside one party."""
    label = el.get("text", "")
    fid = (el.get("ids") or [""])[0]
    if not fid:
        return Item("head", style=el.get("style", ""), label=label, level=LEVEL.get(el.get("style", ""), 0))
    vals: list[str] = []
    b = binding(fid)
    if b is not None:
        # read the data points by name inside the party, without the
        # role discriminators the document-wide reading needs
        parts: list[tuple[str, str]] = []
        for dp in b.data_points:
            name = dp.get("mismo")
            if not name:
                continue
            for node in ctx.scope.iter(f"{M}{name}"):
                if node.text and node.text.strip() and (name, node.text.strip()) not in parts:
                    parts.append((name, node.text.strip()))
        if label == "Company Address":
            vals = _address_lines(ctx.scope)
        elif parts:
            vals = [bind.display_value(parts, b)]
    item = Item("row", style=el.get("style", ""), label=label, values=[v for v in vals if v],
                level=LEVEL.get(el.get("style", ""), 0), visible=bool([v for v in vals if v]))
    if ctx.edit and b is not None and ctx.scope is not None:
        dp = next((d for d in b.data_points if d.get("mismo") and not d.get("attribute")), {})
        cls = f"r l{item.level}" + (" b" if item.style == "TXR-B" else "")
        key = bind.stable_path(ctx.scope)
        attrs = (f" data-tf='{esc(fid)}' data-tk='{esc(key)}' data-tdp='{esc(dp.get('mismo', ''))}'")
        first = (item.values or [""])[0] if label != "Company Address" else (_address_lines(ctx.scope) or [""])[0]
        if point_choices(dp):
            ctl = f"<span class='v pick'{attrs} tabindex='0' role='button'>{esc(first)}</span>"
        else:
            ctl = f"<span class='v'{attrs} contenteditable='true' spellcheck='false'>{esc(first)}</span>"
        if label == "Company Address":
            # the whole address is edited where it prints: street, then city,
            # state and ZIP on the line below -- each its own data point
            addr = ctx.scope.find(f".//{M}ADDRESS")
            def part(name: str, hint: str) -> str:
                value = addr.findtext(f"{M}{name}", "").strip() if addr is not None else ""
                return (f"<span class='v addrpart' data-tf='{esc(fid)}' data-tk='{esc(key)}'"
                        f" data-tdp='{name}' data-ph='{hint}' contenteditable='true'"
                        f" spellcheck='false'>{esc(value)}</span>")
