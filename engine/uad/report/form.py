def _sized_families(css: str) -> str:
    """Give every rule that sets a size the Myriad Pro kerned for that size.

    The samples' letter spacing differs by point size, so each size has its own
    font family (``kerned_fonts``); a rule that sets ``font-size:Npt`` also
    names ``UAD N``.  Text that inherits its size inherits the family with it.
    """
    from . import kerned_fonts

    def add(match):
        size = float(match.group(1))
        return f"font-size:{match.group(1)}pt;font-family:'UAD {size:g}',{fonts.FALLBACK}"

    # a rule that already names a face (the Wingdings checkboxes) keeps it
    out = []
    for chunk in re.split(r"(\})", css):
        if "font-size:" in chunk and "font-family" not in chunk:
            chunk = re.sub(r"font-size:([\d.]+)pt", add, chunk)
        out.append(chunk)
    body = "".join(out)
    return "\n".join([
        kerned_fonts.css(),
        body,
        "body{font-family:'UAD 9'," + fonts.FALLBACK + ";font-kerning:normal;"
        "font-feature-settings:'kern' 1,'liga' 1;text-rendering:geometricPrecision}",
    ])


