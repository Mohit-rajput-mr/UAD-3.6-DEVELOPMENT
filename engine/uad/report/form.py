def _exhibits(ctx: Ctx, section: str) -> list[dict]:
    cats = image_categories()
    out = []
    filled = {m["fills"]: m for m in ctx.media if m.get("fills")}
    for im in _images(ctx):
        sec, caption = cats.get(im["category"], ("", ""))
        owner = im["owner"]
        if not im["category"] and owner is not None:
            sec = {"PROPERTY_UNIT": "Unit Interior", "AMENITY": "Subject Property Amenities",
                   "CAR_STORAGE": "Vehicle Storage", "DEFECT": ""}.get(_local(owner), "")
        if im["category"] in ("PropertyPhoto",):
            continue
        if im["category"] == "SalesComparableMap":
            sec = "Sales Comparison Approach"
        if im["category"] == "DwellingFront" and section == "Dwelling Exterior":
            pass
        if sec != section:
            continue
        if ctx.scope is not None:
            # This copy of the section is one unit, one structure or one
            # outbuilding, so only the images inside it belong to it -- without
            # this every unit prints every unit's photographs.
            tree = ctx.scope.getroottree()
            if not tree.getpath(im["node"]).startswith(tree.getpath(ctx.scope) + "/"):
                continue
        title = im["caption"] or caption
        src = _data_uri(im["path"])
        fill = filled.get(im["location"]) if im["location"] else None
        if fill is not None:
            # The appraiser's photo in the document's own box.  A template's
            # boxes carry the D-1 samples' "This is where the ... photo would
            # display" pictures, which are exactly what gets replaced.
            src = _data_uri(Path(fill["path"]))
        out.append({"src": src, "title": caption or title,
                    "caption": im["caption"] if caption else "",
                    "location": im["location"], "category": im["category"],
                    "layout": layout_of(im["category"]),
                    "media_id": fill.get("media_id", "") if fill else "",
                    # the document's own IMAGE: named, replaced and removed in place
                    "image_key": bind.stable_path(im["node"]), "raw_caption": im["caption"]})
    for m in ctx.media:
        # The subject's front photo and a comparable's thumbnail have slots of
        # their own; filing them under a section does not make them exhibits.
        if m.get("category") in ("subject", "comparable") or m.get("fills"):
            continue
        category = media_category(m)
        home = ("Sketch" if category in SKETCH else
                "Sales Comparison Approach" if category == "SalesComparableMap" else
                m.get("section_name"))
        if home == section:
            title = m.get("caption", "")
            if category in SKETCH and not title:
                title = cats.get(category, ("", ""))[1]
            # a map sets full page wherever it is filed (Appendix E p31)
            layout = "full" if m.get("category") == "map" else layout_of(category)
            out.append({"src": _data_uri(Path(m["path"])), "title": title,
                        "caption": "", "media_id": m.get("media_id", ""), "named": True,
                        "category": category, "layout": layout})
    number = SECTION_NUMBER.get(section, 0)
    for slot in ctx.slots:
        if int(slot.get("section") or 0) == number:
            out.append({"src": "", "title": str(slot.get("caption") or ""), "caption": "",
                        "slot": str(slot["id"]), "named": True})
    return out


