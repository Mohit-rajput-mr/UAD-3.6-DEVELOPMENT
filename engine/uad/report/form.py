    target = _relations(ctx.root).get(defect.get(f"{XLINK}label"))
    want = DEFECT_TARGETS.get(category.split(" - ")[0], "?")
    if want == "?":
        return True
    kind = _local(target) if target is not None else None
    if want != kind:
        return False
    if target is not None and want == "IMPROVEMENT":
        imp_kind = _find_text(target, "ImprovementType")
        if category.startswith("Outbuilding") != (imp_kind == "Outbuilding"):
            return False
    if ctx.scope is not None and target is not None and _local(ctx.scope) == kind:
        if target is not ctx.scope and target.getroottree().getpath(target) !=                 ctx.scope.getroottree().getpath(ctx.scope):
            return False
    if section == "Summary":
        action = _find_text(defect, "DefectItemRecommendedActionType")
        if action in ("", "None"):
            return False
    return True


