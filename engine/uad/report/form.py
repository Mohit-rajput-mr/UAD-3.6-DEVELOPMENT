NUMBER = re.compile(r"^\d{1,2}\.$")
# Wording that belongs to one government programme prints only for that
# programme (B-1 gives these paragraphs an agency condition, but files several
# of them under one field, so the paragraph's own wording decides which).
AGENCIES = {"FHA": ("FHA", "Mortgagee", "HUD"), "USDA": ("USDA",), "VA": ("VA",)}


def _agency_ok(ctx: Ctx, text: str) -> bool:
    got = {v for v in rules.values_of(ctx.root, "GovernmentAgencyAppraisalType")}
    for agency, words in AGENCIES.items():
        if any(re.search(rf"{w}", text) for w in words):
            return agency in got
    return True


def _anchor_gate(ctx: Ctx, fid: str) -> bool:
    """Whether the paragraphs under this margin slot print.

    The slot's field carries B-1's rule for the paragraph that follows.  Where
    B-1 states a rule once, on a block's heading (29.054, "Display when
    PartyRoleType = AppraiserSupervisor"), the slots under it carry none of
    their own and stay out with it: a slot that decides sets the state for the
    block, a slot that does not inherits a hidden one.
    """
    for rule in _fields().get(fid, {}).get("display_rules", []):
        decided = rules.evaluate(rule.get("rule", ""), ctx.root)
        if decided.known:
            ctx.placeholders["block_shown"] = "1" if decided.shown else "0"
            return decided.shown
    return ctx.placeholders.get("block_shown") != "0"


def _fixed_text(out: list[Block], printed: str, el: dict, ctx: Ctx) -> None:
    """One paragraph of the report's own fixed wording.

    The Certifications and Scope of Work pages are wording the GSEs set, not
    data: C-1 marks each paragraph with a slot in the margin whose field
    carries the display rule (``Always displays``, or a condition on the
    assignment), and the paragraph prints only when that rule says so.
    """
    text = " ".join(str(el.get("text", "")).split())
    if not text:
        return
    fid = ctx.placeholders.get("rule_fid", "")
    shown = _anchor_gate(ctx, fid)
    if shown and not _agency_ok(ctx, text):
        shown = False
    numbered = bool(NUMBER.match(text))
    prev = out[-1] if out else None

    cls = "txc np" if numbered else "txc"
    out.append(Block("static", section=printed, visible=shown, fids=[fid],
                     html=f"<div class='{cls}'>{esc(text)}</div>"))


def _party_item(el: dict, ctx: Ctx) -> Item:
    """A contact row read inside one party."""
    label = el.get("text", "")
    fid = (el.get("ids") or [""])[0]
    if not fid:
        return Item("head", style=el.get("style", ""), label=label, level=LEVEL.get(el.get("style", ""), 0))
    vals: list[str] = []
    b = binding(fid)
    if b is not None:
        # read the data points by name inside the party, without the
        # role discriminators the document-wide reading needs
        parts: list[tuple[str, str]] = []
        for dp in b.data_points:
            name = dp.get("mismo")
            if not name:
                continue
            for node in ctx.scope.iter(f"{M}{name}"):
                if node.text and node.text.strip() and (name, node.text.strip()) not in parts:
                    parts.append((name, node.text.strip()))
        if label == "Company Address":
            vals = _address_lines(ctx.scope)
        elif parts:
            vals = [bind.display_value(parts, b)]
    item = Item("row", style=el.get("style", ""), label=label, values=[v for v in vals if v],
                level=LEVEL.get(el.get("style", ""), 0), visible=bool([v for v in vals if v]))
    if ctx.edit and b is not None and ctx.scope is not None:
        dp = next((d for d in b.data_points if d.get("mismo") and not d.get("attribute")), {})
        cls = f"r l{item.level}" + (" b" if item.style == "TXR-B" else "")
        key = bind.stable_path(ctx.scope)
        attrs = (f" data-tf='{esc(fid)}' data-tk='{esc(key)}' data-tdp='{esc(dp.get('mismo', ''))}'")
        first = (item.values or [""])[0] if label != "Company Address" else (_address_lines(ctx.scope) or [""])[0]
        if point_choices(dp):
            ctl = f"<span class='v pick'{attrs} tabindex='0' role='button'>{esc(first)}</span>"
        else:
            ctl = f"<span class='v'{attrs} contenteditable='true' spellcheck='false'>{esc(first)}</span>"
        if label == "Company Address":
            # the whole address is edited where it prints: street, then city,
            # state and ZIP on the line below -- each its own data point
            addr = ctx.scope.find(f".//{M}ADDRESS")
            def part(name: str, hint: str) -> str:
                value = addr.findtext(f"{M}{name}", "").strip() if addr is not None else ""
                return (f"<span class='v addrpart' data-tf='{esc(fid)}' data-tk='{esc(key)}'"
                        f" data-tdp='{name}' data-ph='{hint}' contenteditable='true'"
                        f" spellcheck='false'>{esc(value)}</span>")
            ctl = (f"<span class='addrlines'>{ctl}<span class='addr2'>{part('CityName', 'City')}, "
                   f"{part('StateCode', 'ST')} {part('PostalCode', 'ZIP')}</span></span>")
        item = Item("party", style=item.style, label=label, values=item.values, level=item.level,
                    visible=True, fids=[fid],
                    html=f"<div class='{cls}'><span class='lb'>{esc(label)}</span>{ctl}</div>")
    return item


def _address_lines(node: etree._Element | None) -> list[str]:
    if node is None:
        return []
    addr = node.find(f".//{M}ADDRESS")
    if addr is None:
        return []
    line1 = addr.findtext(f"{M}AddressLineText", "").strip()
    unit = addr.findtext(f"{M}AddressUnitIdentifier", "").strip()
    if unit:
        line1 = f"{line1} {addr.findtext(f'{M}AddressUnitDesignatorType', '').strip()} {unit}".strip()
    city = addr.findtext(f"{M}CityName", "").strip()
    state = addr.findtext(f"{M}StateCode", "").strip()
    post = addr.findtext(f"{M}PostalCode", "").strip()
    line2 = ", ".join(x for x in (city, f"{state} {post}".strip()) if x)
    return [x for x in (line1, line2) if x]


def _address(ctx: Ctx) -> str:
    lines = _address_lines(subject(ctx))
    return ", ".join(lines)


