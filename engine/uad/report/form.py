def _images(ctx: Ctx) -> list[dict]:
    """Every IMAGE the case references, with its file resolved if present."""
    out = []
    for img in ctx.root.iter(f"{M}IMAGE"):
        loc = _find_text(img, "ImageFileLocationIdentifier")
        cat = _find_text(img, "ImageCategoryType")
        cap = _find_text(img, "ImageCaptionCommentDescription")
        owner = next((a for a in img.iterancestors() if _local(a) in
                      ("DEFECT", "PROPERTY_UNIT", "AMENITY", "CAR_STORAGE", "IMPROVEMENT",
                       "PROPERTY")), None)
        path = None
        if loc and ctx.folder is not None:
            name = re.split(r"[\\/]", loc.strip().rstrip("\\/"))[-1]
            for cand in (ctx.folder / "Images" / name, ctx.folder / name):
                if name and cand.is_file():
                    path = cand
                    break
        out.append({"node": img, "location": loc, "category": cat, "caption": cap,
                    "owner": owner, "path": path})
    return out


def _data_uri(path: Path | None) -> str:
    if path is None or not path.is_file():
        return ""
    mime = mimetypes.guess_type(path.name)[0] or "image/jpeg"
    return f"data:{mime};base64,{base64.b64encode(path.read_bytes()).decode('ascii')}"


def _photo_for(ctx: Ctx, section: str) -> tuple[str, str]:
    want = {"Summary": "PropertyPhoto", "Dwelling Exterior": "DwellingFront",
            "Subject Property": "PropertyPhoto"}.get(section, "")
    # The front of the dwelling is entered once and redisplays: B-1 gives the
    # Summary photo (1.000.1) the Dwelling Exterior photo (8.000.1) as its
    # source, and the grid's subject thumbnail is the same property photo.
    # A photo the appraiser supplied takes precedence over whatever the
    # document already carried (a template's sample picture, say).
    if section in ("Summary", "Dwelling Exterior", "Subject Property"):
        for m in ctx.media:
            if m.get("category") in ("subject", "photo"):
                src = _data_uri(Path(m["path"]))
                if src:
                    return src, m.get("caption", "")
    for im in _images(ctx) if want else []:
        if im["category"] == want:
            return _data_uri(im["path"]), im["caption"]
    return "", ""


