"""The URAR, drawn from Appendix C-1 and styled to Appendix E.

``engine/spec/c1_form.json`` is the form as C-1 draws it: every tab, bar,
subheading, row, checkbox, table and photo slot, in page order, each carrying
the Report Field IDs that fill it (see ``uad/spec/extract_c1_form.py``).  This
module walks that form against a case and emits exactly the parts the case
fills, in C-1's order and with C-1's geometry, so the report reads as the
GSEs' Appendix D-1 samples do.

What decides whether an element prints:

* a row, checkbox or commentary prints when its field has a value;
* a heading with no field of its own (``Zoning``, ``Credentials``) prints when
  something under it prints;
* a subheading, bar or tab prints when anything in its span prints;
* a table prints the rows that hold data -- a fixed row (``Hazard Zone``) when
  any of its cells has a value, a template row once per instance in the case;
* an exhibits bar prints only with images under it (Appendix E, every section).

Repeating parts of the form -- a Dwelling Exterior per structure, a Unit
Interior per unit, a contact block per party -- are drawn once per instance
with the values read inside that instance.
"""
