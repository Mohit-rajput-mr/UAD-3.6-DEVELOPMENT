NUMBER = re.compile(r"^\d{1,2}\.$")
# Wording that belongs to one government programme prints only for that
# programme (B-1 gives these paragraphs an agency condition, but files several
# of them under one field, so the paragraph's own wording decides which).
AGENCIES = {"FHA": ("FHA", "Mortgagee", "HUD"), "USDA": ("USDA",), "VA": ("VA",)}


def _agency_ok(ctx: Ctx, text: str) -> bool:
    got = {v for v in rules.values_of(ctx.root, "GovernmentAgencyAppraisalType")}
    for agency, words in AGENCIES.items():
        if any(re.search(rf"\b{w}\b", text) for w in words):
            return agency in got
    return True


def _anchor_gate(ctx: Ctx, fid: str) -> bool:
    """Whether the paragraphs under this margin slot print.

    The slot's field carries B-1's rule for the paragraph that follows.  Where
    B-1 states a rule once, on a block's heading (29.054, "Display when
    PartyRoleType = AppraiserSupervisor"), the slots under it carry none of
    their own and stay out with it: a slot that decides sets the state for the
    block, a slot that does not inherits a hidden one.
    """
    for rule in field_entry(fid).get("display_rules", []):
        text = rule.get("rule", "")
        if "alt" in ctx.placeholders:
            # one sentence per alternative of a numbered certification
            parts = [p for p in re.split(r"(?=\bDisplay (?:(?:descriptive|this) text )?when\b)", text) if p.strip()]
            n = int(ctx.placeholders["alt"] or 0)
            if (n >= len(parts) and ctx.placeholders.get("alt_src") == "number"
                    and not rules.ALWAYS.match(parts[0])):
                # A repeated certification number with no sentence of its own
                # is the "otherwise" alternative (B-1 29.041 states only the
                # first of #21's two): it prints when none of the stated ones
                # does.
                said = [rules.evaluate(p, ctx.root, lenient=True) for p in parts]
                if all(d.known for d in said):
                    shown = not any(d.shown for d in said)
                    ctx.placeholders["block_shown"] = "1" if shown else "0"
                    return shown and ctx.placeholders.get("gate") != "0"
            if len(parts) > 1:
                text = parts[min(n, len(parts) - 1)]
        decided = rules.evaluate(text, ctx.root, lenient=True)
        if decided.known:
            ctx.placeholders["block_shown"] = "1" if decided.shown else "0"
            return decided.shown and ctx.placeholders.get("gate") != "0"
    return ctx.placeholders.get("block_shown") != "0" and ctx.placeholders.get("gate") != "0"


def _formula_labels(els: list[dict], slot: dict) -> list[dict]:
    """The label line C-1 sets just above a three-value slot -- a formula
    ("A x B = C") -- or nothing when the slot is not one."""
    y = float(slot.get("y", 0))
    page = slot.get("page")
    line = [e for e in els if e.get("kind") == "row" and not e.get("ids") and e.get("page") == page
            and 0 < y - float(e.get("y", 0)) < 20]
    texts = [e.get("text", "").strip() for e in line]
    if "\u00d7" not in texts or "=" not in texts:
        return []
    return sorted(line, key=lambda e: float(e.get("x0", 0)))


