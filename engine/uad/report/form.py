@lru_cache(maxsize=4096)
def choices_for(fid: str) -> tuple[tuple[str, str], ...]:
    """The values A-1 allows in this field, as (value, what it prints).

    A field the specification enumerates is a list to pick from, not a box to
    type into: typing "Purchse" into Assignment Reason is a compliance finding
    waiting to happen, and the form has always shown these as dropdowns.
    """
    # The list is the one belonging to the data point the value is written to
    # -- the same one ``edit.choose_data_point`` picks -- not whichever data
    # point happens to carry a list.  Year Built is PropertyStructureBuiltYear
    # (a date) beside PropertyStructureBuiltYearEstimatedIndicator (true/false),
    # and taking the first list found offered "true / false" in place of the
    # year, so the year could not be typed at all.
    from .. import edit, entry

    try:
        pf = edit.field(fid)
        dp = edit.choose_data_point(pf.binding)
    except (KeyError, ValueError):
        return ()
    # A measured value keeps its unit in an attribute, and that attribute's
    # enumerations are units ("SquareFeet"), not values: the value is typed.
    if entry.unit_attribute(dp):
        return ()
    return _merged_choices(dp.get("mismo", ""), fid, dp)


def _merged_choices(mismo: str, fid: str, dp: dict) -> tuple[tuple[str, str], ...]:
    """A-1's values for this data point here: the field's own list, widened
    by anything the canonical map defines for this slot.

    A-1 writes its enumeration rows against a Report Location, and a cell
    often packs several, so a value listed once reaches the field it was
    written against and no other.  That is how the amenity rows came to
    offer six of the twenty-seven amenities A-1 allows there, and the
    Defects rows three of eight.  Taking the slot's list *instead* is worse,
    not better -- measured against the twelve D-1 samples and the
    authenticated 18 North St file it drops 90 values that real reports use,
    against 23 today -- because the sheet's per-location lists are narrower
    than what the same place actually accepts.  So the two are unioned:
    nothing a field offered before is lost, and everything A-1 names for the
    slot is gained.
    """
    from .. import uadmap

    shown = dict(uadmap.labels(mismo))
    out: list[tuple[str, str]] = []
    seen: set[str] = set()
    for opt in dp.get("enumerations") or []:
        value = (opt.get("value") or "").strip()
        if value and value not in seen:
            seen.add(value)
            out.append((value, bind.answer_label(value, opt.get("display") or shown.get(value) or value)))
    for value in uadmap.options(mismo, slot=fid):
        if value not in seen:
            seen.add(value)
            out.append((value, bind.answer_label(value, shown.get(value) or value)))
    out.sort(key=lambda pair: pair[1].casefold())
    return tuple(out)


def printed_point(fid: str, shown: str = "") -> str:
    """Which of a field's enumerated data points its list is: the one whose
    value is showing, else the field's principal list (the type, not its
    ownership or an indicator) -- a project amenity row lists AmenityType,
    not AmenityOwnershipType."""
    b = binding(fid)
    enum = [dp for dp in (b.data_points if b else [])
            if dp.get("enumerations") and not dp.get("attribute")]
    if len(enum) < 2:
        return ""
    want = (shown or "").strip()
    if want:
        for dp in enum:
            for e in dp["enumerations"]:
                if want in (e.get("value"), e.get("display")):
                    return dp["mismo"]
    ranked = sorted(enum, key=lambda dp: (("Ownership" in dp["mismo"]) or dp["mismo"].endswith("Indicator"),
                                          -len(dp["enumerations"])))
    return ranked[0]["mismo"]


