@lru_cache(maxsize=2048)
def _bracketed_beside(fid: str) -> bool:
    """B-1 says a second value of the field prints in brackets beside the
    first: 18.012 "Display in () next to Amenity Type"."""
    return any(re.search(r"Display in \(\) next to", st.get("rule", ""), re.I)
               for st in field_entry(fid).get("display_rules", []))


# B-1 18.066-18.068: 'Display "Greatest Number of Units Owned-" and value'
_PREFIX = re.compile(r'Display\s+[“"](?P<text>[^”"]+)[”"]\s+and\s+(?:the\s+)?value', re.I)


@lru_cache(maxsize=2048)
def label_prefix(fid: str) -> str:
    for st in field_entry(fid).get("display_rules", []):
        m = _PREFIX.search(st.get("rule", ""))
        if m:
            return m["text"].strip()
    return ""


def with_label_prefix(fid: str, value: str) -> str:
    """The value as B-1 prints it with its own words before it: D-1 Condo1
    "Greatest Number of Units Owned - 2", Coop1 "Prior Use: Apartment"."""
    prefix = label_prefix(fid)
    if not prefix:
        return value
    if prefix.endswith("-"):
        return f"{prefix[:-1].rstrip()} - {value}"
    return f"{prefix} {value}"


_PAREN = re.compile(r"^When (?P<cond>[^:]+):.*?Display (?P<text>\([^)]+\)) in parenthesis on the right", re.I)


def _paren_suffix(ctx: "Ctx", fid: str) -> str:
    """B-1's "When <condition>: Display (X) in parenthesis on the right" for a
    static ID beside a value (26.074: "$548,999 (Cooperative Interest)"); the
    Summary's copy (1.085) is the Reconciliation's, per summary_sources."""
    src = summary_sources().get(fid, {}).get("sources") or [fid]
    for f in src:
        for st in field_entry(f).get("display_rules", []):
            m = _PAREN.match(" ".join(st.get("rule", "").split()))
            if m:
                cond = m["cond"].replace("“", '"').replace("”", '"')
                d = rules.evaluate("Display when " + cond, ctx.root, ctx.scope)
                return m["text"] if d.known and d.shown else ""
    return ""


_WHEN_ITALIC = re.compile(r"^When (?P<cond>[^:]+):.*Display text in italics", re.I)


def _italic_when(ctx: "Ctx", fid: str) -> bool | None:
    """A static note's own B-1 condition, "When <condition>: ... Display text
    in italics ...", decided against the document; None when it has none."""
    for st in field_entry(fid).get("display_rules", []):
        m = _WHEN_ITALIC.match(" ".join(st.get("rule", "").split()))
        if m:
            cond = m["cond"].replace("“", '"').replace("”", '"')
            d = rules.evaluate("Display when " + cond, ctx.root, ctx.scope)
            return d.shown if d.known else None
    return None


def field_rule_hides(ctx: "Ctx", fid: str) -> bool:
    """A field's B-1 display rule says, against this document, that it does
    not display: every statement that is a "Display ... when <data point
    comparison>" decides false, read inside the section copy's scope.  A rule
    that decides nothing (prose, an unparsed form) never hides anything."""
    said = []
    for st in field_entry(fid).get("display_rules", []):
        text = st.get("rule", "")
        if not _DISPLAY_WHEN.match(text):
            continue
        # only the condition: B-1 goes on with presentation notes ("- Display
        # Street Access Type ...", "Note: ...", "(Figure 4 - 4)", "When ... = 0
        # checkboxes do not display")
        text = re.split(r"\s[\u2212\u2013-]\s|\sNote:|\(Figure|\.\s|\sWhen\s|\sIf\s", text)[0]
        if "do not display" in text.lower() or "@" in text:
            continue                       # an inverse rule, or one on an attribute: not read here
        # "Display checkboxes on each instance of Unit Interior when ..."
        # (10.011): what displays is said before "when"; the condition is after
        text = _DISPLAY_WHEN.sub("Display when", text, count=1)
        d = rules.evaluate(text, ctx.root, ctx.scope)
        if not d.known:
            return False
        said.append(d.shown)
    return bool(said) and not any(said)


# B-1 4.039: "When there is only 1 view, (Primary) does not display"
_ALONE = re.compile(r"When there is only (?:1|one) \w+,?\s+(\([^)]+\)) does not display", re.I)


@lru_cache(maxsize=2048)
def alone_hidden(fid: str) -> str:
    """The modifier B-1 drops from a table row when the row is the only one."""
    for st in field_entry(fid).get("display_rules", []):
        m = _ALONE.search(st.get("rule", ""))
        if m:
            return m.group(1)
    return ""


_ZERO_RULE = re.compile(r"\bif\s+(?:the\s+value\s+is\s+)?zero,?\s+do\s+not\s+display", re.I)


@lru_cache(maxsize=2048)
def hides_zero(fid: str) -> bool:
    """B-1 states it per field: "If zero, do not display the row"."""
    return any(_ZERO_RULE.search(st.get("rule", "")) for st in field_entry(fid).get("display_rules", []))


def _is_zero(text: str) -> bool:
    m = re.search(r"-?\d[\d,]*(?:\.\d+)?", text or "")
    return bool(m) and float(m.group(0).replace(",", "")) == 0


def _label_fill(label: str, ctx: Ctx) -> str:
    """Resolve the bracketed placeholders C-1 prints in a label."""
    subs = {"[Structure Identifier]": ctx.placeholders.get("structure", ""),
            "[Unit Identifier]": ctx.placeholders.get("unit", ""),
            "[Outbuilding Type]": ctx.placeholders.get("outbuilding", "")}
    for k, v in subs.items():
        if k in label:
            label = label.replace(f" - {k}", f" - {v}" if v else "").replace(k, v)
    label = re.sub(r"\s*\(\s*\)", "", label)
    return " ".join(label.split())


def _column_item(el: dict, ctx: Ctx) -> Item:
    kind = el["kind"]
    label = _label_fill(el.get("text", ""), ctx)
    ids = resolve(el.get("ids", []), el.get("text", ""))
    style = el.get("style", "")
    if kind == "row":
        if not ids:
            return Item("head", style=style, label=label, level=LEVEL.get(style, 0))
        pairs = shown_pairs(ctx, ids[0]) if len(ids) == 1 else []
        values = [t for t, _k in pairs] if len(ids) == 1 else [text_of(ctx, ids)] if text_of(ctx, ids) else []
        if values and len(ids) == 1 and hides_zero(ids[0]) and all(_is_zero(v) for v in values):
            values, pairs = [], []        # B-1: "If zero, do not display the row" (10.004, 10.007)
        if values and not ctx.edit and len(ids) == 1 and field_rule_hides(ctx, ids[0]):
            values, pairs = [], []        # B-1's own "Display when ..." for the field is false
        if label.startswith("Total Estimated Cost of Items") and cost_to_repair_type(ctx) != "TotalCost":
            values = []
        suffix = next((x for x in (_paren_suffix(ctx, f) for f in el.get("ids", [])) if x), "")
        if ctx.edit and values and set(ids) & YEARS_FIDS and not suffix:
            suffix = "years"      # printed after the number, never typed (B-1 p351)
        item = Item("row", style=style, label=label, values=values,
                    level=LEVEL.get(style, 0),
                    visible=bool(values) or ctx.edit, fids=ids, suffix=suffix if values else "")
        item.keys = [k for _t, k in pairs]
        return item
    if kind == "head":
        return Item("head", style=style, label=label, level=LEVEL.get(style, 0))
    if kind == "check":
        value = checkbox(ctx, ids[0], label) if ids else None
        if not ctx.edit and ids and field_rule_hides(ctx, ids[0]):
            value = None          # B-1's own rule for the field says it does not display
        return Item("check", style=style, label=label, checked=value,
                    yes_no=el.get("yes_no", False), level=LEVEL.get(style, 0),
                    visible=value is not None or (ctx.edit and bool(ids)),
                    fids=ids)
    if kind == "prose":
        value = text_of(ctx, ids, " ")
        return Item("prose", style="TXC-B1", label=label, values=[value] if value else [],
                    visible=bool(value) or (ctx.edit and bool(ids)), fids=ids)
    if kind == "italic":
        return Item("italic", style="TXC-I1", label=label, level=0)
    if kind == "photo":
        return Item("photo", fids=ids)
    return Item("head", label=label)


def build(tree, *, folder: Path | None = None, media: list[dict] | None = None,
          sample: bool = False, edit: bool = False,
          slots: list[dict] | None = None,
          imported: Iterable[str] | None = None) -> list[Block]:
    """Every block of the report for one case, in order, with visibility set."""
    root = tree.getroot() if hasattr(tree, "getroot") else tree
    ctx = Ctx(root, None, folder, list(media or []), edit=edit,
              slots=list(slots or []) if edit else [],
              imported=frozenset(imported or ()))
    from .. import report_types
    kind = report_types.kind_of(root)
    if kind != report_types.URAR:
        return _build_kind(kind, ctx, sample=sample)
    elements: list[dict] = []
    for pg in form()["pages"]:
        for el in pg["elements"]:
            elements.append({**el, "page": pg["page"]})

    # split into sections at each tab; the Summary is everything before the first
    sections: list[tuple[str, list[dict]]] = [("Summary", [])]
    for el in elements:
        if el["kind"] == "tab":
            sections.append((el["title"], [el]))
            continue
        if el["page"] == 40 and sections[-1][0] == "Supplemental Information" and \
                not any(e.get("page") == 40 for e in sections[-1][1]):
            sections.append(("Certifications and Scope of Work", []))
        sections[-1][1].append(el)

    # More than one dwelling: each Dwelling Exterior is followed by the Unit
    # Interiors of the units in it (D-1 2-4: Building 1, its Unit 1, Building
    # 2, its Unit 2 -- the order B-1 p377 gives the defects table too).
    unit_title, unit_els = next(((t, e) for t, e in sections if t.split(" - [")[0] == "Unit Interior"),
                                ("", []))
    interleave = len(improvements(ctx, "Dwelling")) > 1 and unit_els \
        and section_shown(ctx, "Unit Interior") is not False
    placed: set[str] = set()
    blocks: list[Block] = []
    for title, els in sections:
        base = title.split(" - [")[0]
        if section_shown(ctx, base) is False:
            continue
        if not ctx.edit and print_gate(ctx, base) is False:
            continue
        for sctx, printed in section_instances(ctx, title):
            if base == "Unit Interior" and sctx.scope is not None and bind.stable_path(sctx.scope) in placed:
                continue
            if base == "Cost Approach":
                blocks += _cost_approach(title, printed, els, sctx, sample=sample)
                continue
            blocks += _section(title, printed, els, sctx, sample=sample)
            if interleave and base == "Dwelling Exterior" and sctx.scope is not None:
                for uctx, uprinted in section_instances(ctx, unit_title):
                    imp = next(uctx.scope.iterancestors(f"{M}IMPROVEMENT"), None) \
                        if uctx.scope is not None else None
                    if imp is sctx.scope:
                        placed.add(bind.stable_path(uctx.scope))
                        blocks += _section(unit_title, uprinted, unit_els, uctx, sample=sample)
    _resolve_visibility(blocks)
    return blocks


def _cost_approach(title: str, printed: str, els: list[dict], ctx: Ctx, *, sample: bool) -> list[Block]:
    """The Cost Approach with a "Depreciated Cost" block per improvement.

    C-1 draws one dwelling block (25.005-25.022) and one outbuilding block
    (25.023-25.036); B-1 repeats them per dwelling and per outbuilding, each
    reading the IMPROVEMENT_COST_AND_DEPRECIATED_VALUE its arc ties to that
    improvement.  Read once for the whole report, D-1 MH1's dwelling table
    carried the barn's and the garage's cost lines too."""
    def at(fid: str) -> int:
        return next((n for n, e in enumerate(els) if e.get("kind") == "h1" and fid in (e.get("ids") or [])), -1)
    d0, o0 = at("25.005"), at("25.023")
    o1 = next((n for n in range(o0 + 1, len(els)) if els[n].get("kind") == "h1"), len(els)) if o0 >= 0 else -1
    if d0 < 0 or o0 < d0 or o1 < 0:
        return _section(title, printed, els, ctx, sample=sample)
    out = _section(title, printed, els[:d0], ctx, sample=sample)

    def costed(imp) -> bool:
        return _arc_linked(imp, "IMPROVEMENT_COST_AND_DEPRECIATED_VALUE") is not None

    dwellings = [imp for imp in improvements(ctx, "Dwelling") if costed(imp)]
    for imp in dwellings:
        sid = _find_text(imp, "StructureIdentifier") if len(dwellings) > 1 else ""
        out += _section(title, printed, els[d0:o0], ctx.inside(imp, structure=sid), sample=sample)
    sheds = []
    for imp in improvements(ctx, "Outbuilding"):
        if costed(imp):
            kind = _find_text(imp, "OutbuildingTypeOtherDescription") or bind._humanise(_find_text(imp, "OutbuildingType"))
            sheds.append((kind, imp))
    for kind, imp in sorted(sheds, key=lambda p: p[0]):
        out += _section(title, printed, els[o0:o1], ctx.inside(imp, outbuilding=kind), sample=sample)
    out += _section(title, printed, els[o1:], ctx, sample=sample)
    return out


def _build_kind(kind: str, ctx: Ctx, *, sample: bool) -> list[Block]:
    """A Restricted Appraisal Update or Completion Report, drawn from its own
    Layout appendix (C-2 / C-3) with the URAR's own section machinery.

    Its sections are not the URAR's: none of B-1's section rules applies, and
    a tab opens a page only where the Layout starts one with it.  What prints
    within a section follows the same rule as the URAR -- an answered field
    prints, an unanswered one keeps its place only in the editor."""
    from .. import report_types
    toc = list(report_types.spec(kind)["sections"].values())

    def toc_name(tab: str) -> str:
        return next((t for t in toc if t == tab), None) or next(
            (t for t in toc if t.startswith(tab)), tab)

    # (section as B-x names it, tab as the Layout prints it, elements, opens a page)
    sections: list[list] = []
    for pg in report_types.form(kind)["pages"]:
        els = [{**el, "page": pg["page"]} for el in pg["elements"]]
        tabs = [e for e in els if e["kind"] == "tab"]
        if els and els[0]["kind"] == "h1" and tabs:
            # C-2 / C-3 open their last section's page with its first subsections
            # (Scope of Work, Intended Use) and set the tab below them, as C-1
            # does on its page 40: they are that section's, not the one before,
            # and the section opens a page (D-2 AU1 p2, D-3 CR2 p3).  Every
            # other section flows on: a Layout page is a drawing, not a break.
            sections.append([toc_name(tabs[0]["title"]), tabs[0]["title"], [], True])
        for i, el in enumerate(els):
            if el["kind"] == "tab":
                name = toc_name(el["title"])
                if sections and sections[-1][0] == name and not any(
                        e["kind"] == "tab" for e in sections[-1][2]):
                    sections[-1][2].append(el)
                    continue
                sections.append([name, el["title"], [el], False])
            elif sections:
                sections[-1][2].append(el)
    blocks: list[Block] = []
    for title, printed, els, opens_page in sections:
        out = _section(title, printed, els, ctx, sample=sample, report=kind)
        if out and opens_page and blocks:
            out[0].new_page = True
        blocks += out
    _resolve_visibility(blocks)
    return blocks


