# ---------------------------------------------------------------------------
def galley_html(blocks: list[Block], edit: bool = False) -> str:
    parts = []
    prev_visible = None
    skipped = False
    for n, blk in enumerate(blocks):
        if not blk.visible:
            skipped = skipped or prev_visible is not None
            continue
        gap = (blk.kind == "cols" and prev_visible is not None and prev_visible.kind == "cols"
               and skipped)
        prev_visible, skipped = blk, False
        attrs = (f" data-n='{n}' data-kind='{blk.kind}' data-group='{blk.group}'"
                 f" data-section='{esc(blk.section)}'"
                 + (" data-newpage='1'" if blk.new_page else ""))
        if blk.kind == "tab":
            parts.append(f"<div class='blk tabblk'{attrs}><div class='tabwrap'>"
                         f"<span class='tab'>{esc(blk.title)}</span></div></div>")
        elif blk.kind == "cols":
            # B-1: the Summary is redisplayed from the rest of the report, so
            # the editor shows it but does not take values typed into it.
            derived = edit and section_number(blk.section) == 1
            left = "".join(_item_html(i, edit and not derived, derived) for i in blk.left if i.visible)
            right = "".join(_item_html(i, edit and not derived, derived) for i in blk.right if i.visible)
            parts.append(f"<div class='blk cols{' gap' if gap else ''}'{attrs}><div class='col left'>{left}</div>"
                         f"<div class='col right'>{right}</div></div>")
        else:
            parts.append(f"<div class='blk solid {blk.kind}'{attrs}>{blk.html}</div>")
    return "".join(parts)


