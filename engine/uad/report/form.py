def repeats_as_list(fid: str) -> bool:
    """A single enumerated data point inside a block A-1 repeats: the field
    takes several values, one instance each."""
    b = binding(fid)
    points = [dp for dp in (b.data_points if b else []) if dp.get("mismo") and not dp.get("attribute")]
    enum = [dp for dp in points if dp.get("enumerations")]
    if enum:
        principal = printed_point(fid) or enum[0]["mismo"]
        enum = [dp for dp in enum if dp["mismo"] == principal][:1]
    if len(enum) != 1:
        return False
    rep = bind.repeating_container(enum[0].get("xpath", ""))
    if enum[0].get("requires"):
        # a condition on the block around the list is not a condition on the
        # list (18.013 Utilities Included: the AssociationDues charge's
        # utilities -- D-1 Condo1 "Sanitary Sewer | Water"); one on the
        # repeating block itself picks an instance and is not a list.  Only
        # for a field C-1 draws as a row: a table's cells (walls, roof) are
        # read a row per block by their own drawer
        from .. import uadmap
        if fid not in _c1_row_fields() or any(
                f"/{rep}/" in pl.get("xpath", "") for k in enum[0]["requires"]
                for pl in uadmap.placements(k)):
            return False
    # the value's own element is what repeats (PROJECT_AMENITY/AmenityType),
    # not merely a block somewhere above it
    return rep == enum[0].get("container")


def _picker(fid: str, shown: str, ordinal: int = 0, adding: bool = False, key: str = "") -> str:
    """An enumerated value, as the list it has to come from.

    Not a native ``<select>``: the page is laid out at three times size and
    scaled back down by a transform, and a browser draws a select's popup at
    the element's computed size without the transform -- so the list came up
    three times too big and covered half the report.  This is an ordinary span
    whose list is drawn inside the page, and therefore scales with it.
    """
    if not choices_for(fid):
        return ""
    extra = f" data-ordinal='{ordinal}'" if ordinal else ""
    dp = printed_point(fid, shown) or next(
        (d["mismo"] for d in (binding(fid).data_points if binding(fid) else [])
         if d.get("enumerations") and not d.get("attribute")), "")
    if key:
        # written into the block this value came from -- or, adding, a new
        # block beside it -- through the table-cell route
        extra += f" data-tf='{esc(fid)}' data-tdp='{esc(dp)}'"
        extra += f" data-tnew='1' data-tscope='{esc(key)}'" if adding else f" data-tk='{esc(key)}'"
    elif printed_point(fid, shown):
        extra += f" data-tdp='{esc(dp)}'"
    if adding:
        extra += " data-ph='+ another'"
    return (f"<span class='v pick{' adding' if adding else ''}' data-fid='{esc(fid)}'{extra} tabindex='0'"
            f" role='button' aria-haspopup='listbox'>{esc(shown)}</span>")


def kind_of_point(dp: dict) -> str:
    """What kind of input a data point takes, from A-1's format: the editor
    draws each kind differently so an appraiser sees, before typing, whether a
    place wants words, an amount, a number, a date or a pick from a list."""
    if not dp:
        return "text"
    kind = (dp.get("format_type") or "").strip().casefold()
    details = (dp.get("format_details") or "").upper()
    name = dp.get("mismo", "")
    # the format first: a measure carries its unit list as enumerations but is
    # typed as a number (Site Size, Finished Area)
    if kind in ("enumerated", "boolean"):
        return "pick"
    if kind == "date":
        return "date" if "DD" in details else "month" if "MM" in details else "year"
    if kind == "amount":
        return "amount"
    if kind == "numeric":
        return "percent" if name.endswith("Percent") else "year" if name.endswith("Year") else "number"
    if dp.get("enumerations") and not kind:
        return "pick"
    return "text"


@lru_cache(maxsize=4096)
def input_kind(fid: str, point: str = "") -> str:
    b = binding(fid)
    points = [d for d in (b.data_points if b else []) if d.get("mismo")]
    if point:
        dp = next((d for d in points if d.get("mismo") == point), None)
        return kind_of_point(dp or {})
    # a field of several points is typed as its main value: Site Size is an
    # area with a unit list, Proximity a distance with a direction, Contract
    # Date a date with an "unknown" box -- the value decides, not the qualifier
    kinds = {kind_of_point(d) for d in points
             if not d.get("attribute") or d["attribute"].endswith("UnitOfMeasureType")}
    if any(d.get("mismo") in ("AddressLineText", "FullName", "CompanyName") for d in points):
        return "text"           # an address or a name, whatever lists ride along (State)
    for k in ("amount", "date", "month", "year", "percent", "number", "pick", "text"):
        if k in kinds:
            return k
    return "text"


def _edit_attrs(item: Item, index: int = 0) -> str:
    """What an editable value needs to write itself back.

    The report is the form: rather than build a second page that resembles it,
    the value a reader sees carries the Report Field ID behind it and is typed
    into where it stands, so the layout an appraiser fills in is the layout
    that prints, to the point.
    """
    if not item.fids:
        return ""
    fid = item.fids[min(index, len(item.fids) - 1)]
    from .. import parties
    name = (" data-name='1'" if parties.name_role(fid) and parties.allows_entity(fid)
            and parties.allows_person(fid) else "")
    return (f" data-fid='{esc(fid)}' data-k='{input_kind(fid)}' contenteditable='true'"
            f" spellcheck='false'{name}")


def _item_html(item: Item, edit: bool = False, derived: bool = False) -> str:
    """One row, heading or checkbox.

    ``derived`` is the Summary in the editor: shown as it prints, never typed
    into, each value pointing at the field it is redisplayed from.
    """
    if item.kind == "row":
        lines = item.values or [""]
        cls = f"r l{item.level}" + (" b" if item.style == "TXR-B" else "")
        if derived and item.fids:
            attrs = _derived_attrs(item.fids)
            return "".join(
                f"<div class='{cls}'><span class='lb'>{esc(item.label) if n == 0 else ''}</span>"
                f"<span class='v derived'{attrs}>{esc(line)}"
                f"{' ' + esc(item.suffix) if item.suffix and n == 0 else ''}</span></div>"
                for n, line in enumerate(lines))
        if edit and item.fids:
            pick = _picker(item.fids[0], lines[0])
            if pick:
                # A list answered more than once (a project's amenities, the
                # licences an appraiser holds) is one list per value, and a
                # field A-1 repeats offers the next one.
                many = [v for v in (item.values or []) if v]
                keys = list(item.keys or [])
                if (len(many) > 1 or repeats_as_list(item.fids[0])) and many                         and len(keys) == len(many) and all(keys):
                    picks = "".join(
                        (f"<div class='{cls}'><span class='lb'>{esc(item.label) if n == 0 else ''}</span>"
                         f"{_picker(item.fids[0], value, key=keys[n])}</div>")
                        for n, value in enumerate(many))
                    if repeats_as_list(item.fids[0]):
                        picks += (f"<div class='{cls}'><span class='lb'></span>"
                                  f"{_picker(item.fids[0], '', adding=True, key=keys[-1])}</div>")
                    return picks
                return (f"<div class='{cls}'><span class='lb'>{esc(item.label)}</span>"
                        f"{pick}</div>")
        attrs = _edit_attrs(item) if edit else ""
        if item.suffix:
            # static text after the value, in the value's own cell but not
            # part of what is typed: "$548,999 (Cooperative Interest)"
            first = (f"<span class='v'><span{attrs}>{esc(lines[0])}</span> "
                     f"{esc(item.suffix)}</span>")
        else:
            first = f"<span class='v'{attrs}>{esc(lines[0])}</span>"
        out = [f"<div class='{cls}'><span class='lb'>{esc(item.label)}</span>{first}</div>"]
        for n, extra in enumerate(lines[1:], start=1):
            more = _edit_attrs(item, n) if edit else ""
            out.append(f"<div class='{cls}'><span class='lb'></span>"
                       f"<span class='v'{more}>{esc(extra)}</span></div>")
        return "".join(out)
    if item.kind == "head":
        ruled = item.style in ("TXR-B", "TXR-I", "TXR-II") and item.level >= 0
        cls = f"hd l{item.level}" + (" b" if item.style in ("TXR-B", "TX-B") else "") + (" ruled" if item.style.startswith("TXR") else "")
        return f"<div class='{cls}'>{esc(item.label)}</div>"
    if item.kind == "check":
        yn = "<div class='yn'><b>Yes</b><b>No</b></div>" if item.yes_no else ""
        cls = f"ck l{item.level}" + (" b" if item.style != "CK-1I" else "")
        boxes = _boxes(item.checked, item.fids[0] if (edit and item.fids) else "")
        return (f"{yn}<div class='{cls}'><span class='cl'>{esc(item.label)}</span>"
                f"{boxes}</div>")
    if item.kind == "prose":
        writable = [f for f in item.fids if binding(f) is not None]
        if edit and writable and not derived:
            shown_value = item.values[0] if item.values else ""
            control = _value_control(None, writable[0], shown_value)
            if control is None:
                control = (f"<span class='v multiline' data-fid='{esc(writable[0])}' contenteditable='true'"
                           f" spellcheck='true'>{esc(shown_value)}</span>")
            return (f"<div class='txcb1'><b>{esc(item.label)}&nbsp; </b>"
                    f"{control}</div>")
        return (f"<div class='txcb1'><b>{esc(item.label)}&nbsp; </b>"
                f"{esc(item.values[0] if item.values else '')}</div>")
    if item.kind == "italic":
        return f"<div class='txci1'>{esc(item.label)}</div>"
    return item.html


def _resolve_visibility(blocks: list[Block]) -> None:
    """Headings print when something under them prints."""
    for blk in blocks:
        if blk.kind == "cols":
            for items in (blk.left, blk.right):
                _column_visibility(items)
            blk.visible = any(i.visible and i.kind not in ("head", "italic")
                              for i in blk.left + blk.right)
    # decoration (italic notes, static paragraphs) follows its neighbours
    for i, blk in enumerate(blocks):
        if blk.kind == "static":
            continue
        if blk.decoration:
            nxt = next((b for b in blocks[i + 1:] if b.group == 0 and not b.decoration), None)
            if blk.kind == "italic" and "There are no apparent" in blk.html:
                prv = next((b for b in reversed(blocks[:i]) if b.kind == "table"), None)
                blk.visible = bool(prv is not None and not prv.visible)
            elif blk.kind == "italic":
                # what the note introduces: the next content block, looking
                # past unanswered ones until a heading follows them -- Subject
                # Listing's "Current and/or relevant listings ... (minimum 1
                # year look back)" heads the listing table with two unanswered
                # rows between (D-1 prints it on every sample)
                shown, passed = None, False
                for b in blocks[i + 1:]:
                    if b.group != 0:
                        if passed:
                            break
                        continue
                    if b.decoration:
                        continue
                    if b.visible:
                        shown = b
                        break
                    passed = True
                blk.visible = bool(shown is not None and "class='txc none'" not in shown.html)
            else:
                blk.visible = True
    # groups: h2 < h1 < tab
    for level in (1, 2, 3):
        for i, blk in enumerate(blocks):
            if blk.group != level:
                continue
            vis = False
            for other in blocks[i + 1:]:
                if other.group >= level or other.section != blk.section:
                    # a heading answers for its own section only: the scope of
                    # work's paragraphs (C-1 p40) do not make an empty
                    # Supplemental Information print (D-1 SF5 has none)
                    break
                if other.visible and not other.decoration:
                    vis = True
                    break
            blk.visible = vis



def _column_visibility(items: list[Item]) -> None:
    for i, it in enumerate(items):
        if it.kind != "head":
            if it.kind == "italic":
                prev = items[i - 1] if i else None
                it.visible = bool(prev and prev.visible)
            continue
        vis = False
        for other in items[i + 1:]:
            if other.kind in ("head",) and other.level <= it.level:
                break
            if other.kind in ("row", "check") and other.level <= it.level and it.style != "TX-B":
                break
            if other.kind == "row" and it.style == "TX-B" and other.level == 0:
                break
            if other.visible and other.kind != "head":
                vis = True
                break
        it.visible = vis


