@lru_cache(maxsize=4096)
def enum_label(mismo: str, value: str) -> str:
    """What A-1 prints for an enumerated value (its display text)."""
    if not value:
        return ""
    for entry in _fields().values():
        for dp in entry.get("data_points") or []:
            if dp.get("mismo") != mismo:
                continue
            for e in dp.get("enumerations") or []:
                if e.get("value") == value:
                    return bind.answer_label(value, e.get("display") or value)
    return bind.answer_label(value, bind._humanise(value))


DEFECT_LEAD = "Apparent Defects, Damages, Deficiencies"


def _owner_title(img: "etree._Element") -> str:
    """The bold heading B-1 puts over a photo, from the block it is in."""
    owner = next((a for a in img.iterancestors()
                  if _local(a) in ("ROOM", "INTERIOR_COMPONENT", "DEFECT", "CAR_STORAGE", "AMENITY")), None)
    if owner is None:
        return ""
    kind = _local(owner)

    def val(path: str) -> str:
        return (owner.findtext(path) or "").strip()
    if kind == "ROOM":
        room = val(f"{M}ROOM_DETAIL/{M}RoomType")
        name = val(f"{M}ROOM_DETAIL/{M}RoomTypeOtherDescription") if room == "Other" else enum_label("RoomType", room)
        level = enum_label("LevelType", val(f"{M}ROOM_DETAIL/{M}LevelType"))
        return " - ".join(x for x in (level, name) if x)
    if kind == "INTERIOR_COMPONENT":
        t = val(f"{M}INTERIOR_COMPONENT_DETAIL/{M}ImprovementComponentType")
        return (val(f"{M}INTERIOR_COMPONENT_DETAIL/{M}ImprovementComponentTypeOtherDescription") if t == "Other"
                else enum_label("ImprovementComponentType", t))
    if kind == "DEFECT":
        t = val(f".//{M}DefectComponentLabelType")
        feature = (val(f".//{M}DefectComponentLabelTypeOtherDescription") if t == "Other"
                   else enum_label("DefectComponentLabelType", t))
        # a vehicle storage's or an amenity's defect is titled by its type
        holder = next((a for a in owner.iterancestors() if _local(a) in ("CAR_STORAGE", "AMENITY")), None)
        if holder is None and owner.get(f"{XLINK}label"):
            # kept at property level and tied by its arc (D-1 Condo1:
            # "Apparent Defects, Damages, Deficiencies - Balcony")
            root = owner.getroottree().getroot()
            want = {r.get(f"{XLINK}to") for r in root.iter(f"{M}RELATIONSHIP")
                    if r.get(f"{XLINK}from") == owner.get(f"{XLINK}label")
                    and (r.get(f"{XLINK}arcrole") or "").endswith(("_AMENITY", "_CAR_STORAGE"))}
            holder = next((e for e in root.iter(f"{M}AMENITY", f"{M}CAR_STORAGE")
                           if e.get(f"{XLINK}label") in want), None)
        if holder is not None:
            name = "CarStorageType" if _local(holder) == "CAR_STORAGE" else "AmenityType"
            feature = enum_label(name, (holder.findtext(f".//{M}{name}") or "").strip()) or feature
        return f"{DEFECT_LEAD} - {feature}" if feature else DEFECT_LEAD
    if kind == "CAR_STORAGE":
        return enum_label("CarStorageType", val(f".//{M}CarStorageType"))
    if kind == "AMENITY":
        t = val(f".//{M}AmenityType")
        return val(f".//{M}AmenityTypeOtherDescription") if t == "Other" else enum_label("AmenityType", t)
    return ""


def _exhibits(ctx: Ctx, section: str) -> list[dict]:
    cats = image_categories()
    out = []
    filled = {m["fills"]: m for m in ctx.media if m.get("fills")}
    for im in _images(ctx):
        sec, caption = cats.get(im["category"], ("", ""))
        owner = im["owner"]
        defect_of = None
        if not im["category"] and owner is not None:
            sec = {"PROPERTY_UNIT": "Unit Interior", "AMENITY": "Subject Property Amenities",
                   "CAR_STORAGE": "Vehicle Storage", "DEFECT": ""}.get(_local(owner), "")
            if _local(owner) == "DEFECT":
                # a defect's photo prints in the section of what the defect is
                # in (D-1 2-4: "Apparent Defects, Damages, Deficiencies - Roof"
                # under each building's Dwelling Exterior Exhibits), found by
                # its DEFECT_ContainsDefectOf_* link
                defect_of = _relations(ctx.root).get(owner.get(f"{XLINK}label"))
                sec = _defect_section(defect_of)
        if im["category"] in ("PropertyPhoto",):
            continue
        if im["category"] == "SalesComparableMap":
            sec = "Sales Comparison Approach"
        if im["category"] == "DwellingFront" and section == "Dwelling Exterior":
            pass
        if sec != section:
            continue
        if ctx.scope is not None:
            # This copy of the section is one unit, one structure or one
            # outbuilding, so only the images inside it belong to it -- without
            # this every unit prints every unit's photographs.
            tree = ctx.scope.getroottree()
            if defect_of is not None:
                if defect_of is not ctx.scope:
                    continue
            elif not tree.getpath(im["node"]).startswith(tree.getpath(ctx.scope) + "/") \
                    and not _positional_image(ctx, im, cats):
                continue
        title = im["caption"] or caption
        lead = _owner_title(im["node"])
        if lead:
            # B-1 (10.033, 10.044.1, 10.056, 12.020.1, 13.001.1, 14.002.1 ...):
            # what the photo is of, in bold, then its own caption
            title = " - ".join(x for x in (lead, im["caption"]) if x)
            caption = title
        src = _data_uri(im["path"])
        fill = filled.get(im["location"]) if im["location"] else None
        if fill is not None:
            # The appraiser's photo in the document's own box.  A template's
            # boxes carry the D-1 samples' "This is where the ... photo would
            # display" pictures, which are exactly what gets replaced.
            src = _data_uri(Path(fill["path"]))
        out.append({"src": src, "title": caption or title,
                    # with a lead the caption is already part of the title (D-1
                    # SF1: "Apparent Defects, Damages, Deficiencies - Roof -
                    # Damaged Flashing", printed once)
                    "caption": im["caption"] if caption and not lead else "",
                    "location": im["location"], "category": im["category"],
                    "layout": layout_of(im["category"]),
                    "media_id": fill.get("media_id", "") if fill else "",
                    # the document's own IMAGE: named, replaced and removed in place
                    "image_key": bind.stable_path(im["node"]), "raw_caption": im["caption"]})
    for m in ctx.media:
        # The subject's front photo and a comparable's thumbnail have slots of
        # their own; filing them under a section does not make them exhibits.
        if m.get("category") in ("subject", "comparable", "signature") or m.get("fills"):
            continue                       # (a signature prints on its line)
        category = media_category(m)
        home = ("Sketch" if category in SKETCH else
                "Sales Comparison Approach" if category == "SalesComparableMap" else
                m.get("section_name"))
        if home == section:
            title = m.get("caption", "")
            if category in SKETCH and not title:
                title = cats.get(category, ("", ""))[1]
            # a map sets full page wherever it is filed (Appendix E p31)
            layout = "full" if m.get("category") == "map" else layout_of(category)
            out.append({"src": _data_uri(Path(m["path"])), "title": title,
                        "caption": "", "media_id": m.get("media_id", ""), "named": True,
                        "category": category, "layout": layout})
    number = SECTION_NUMBER.get(section, 0)
    for slot in ctx.slots:
        if int(slot.get("section") or 0) == number:
            out.append({"src": "", "title": str(slot.get("caption") or ""), "caption": "",
                        "slot": str(slot["id"]), "named": True})
    return out


def _defect_section(target: "etree._Element | None") -> str:
    """The report section a defect belongs to, from what its link points at."""
    if target is None:
        return "Site"
    kind = _local(target)
    if kind == "IMPROVEMENT":
        return "Outbuilding" if _find_text(target, "ImprovementType") == "Outbuilding" else "Dwelling Exterior"
    return {"PROPERTY": "Site", "PROPERTY_UNIT": "Unit Interior", "CAR_STORAGE": "Vehicle Storage",
            "AMENITY": "Subject Property Amenities"}.get(kind, "")


def _positional_image(ctx: Ctx, im: dict, cats: dict) -> bool:
    """A photo kept at property level (PROPERTY/INSPECTIONS/.../IMAGE) that
    belongs to a section drawn once per structure.  A-1 gives no link from the
    IMAGE to its IMPROVEMENT; the D-1 2-4 sample holds two DwellingRear images
    (2-4_Dwelling1Rear, 2-4_Dwelling2Rear) and prints one under each
    building, so the n-th such photo is the n-th copy's, and a single one is
    the first copy's (SF1, Condo1: "Dwelling Exterior Exhibits / Dwelling
    Rear").  With more photos than copies nothing is assigned."""
    node = im["node"]
    if any(_local(a) in ("IMPROVEMENT", "PROPERTY_UNIT") for a in node.iterancestors()):
        return False
    kind = _local(ctx.scope)
    if kind not in ("IMPROVEMENT", "PROPERTY_UNIT"):
        return False
    subj = subject(ctx)
    if subj is None:
        return False
    if kind == "IMPROVEMENT":
        imp_type = _find_text(ctx.scope, "ImprovementType")
        copies = [e for e in subj.iter(f"{M}IMPROVEMENT") if _find_text(e, "ImprovementType") == imp_type]
    else:
        copies = list(subj.iter(f"{M}PROPERTY_UNIT"))
    if ctx.scope not in copies:
        return False
    same = [e for e in subj.iter(f"{M}IMAGE")
            if (e.findtext(f"{M}ImageCategoryType") or "").strip() == im["category"]
            and not any(_local(a) in ("IMPROVEMENT", "PROPERTY_UNIT") for a in e.iterancestors())]
    if node not in same or len(same) > len(copies):
        # more photos than copies (MH1: three OutbuildingExhibit images, two
        # outbuildings) -- position says nothing about which is whose
        return False
    return same.index(node) == copies.index(ctx.scope)


#: B-3 p30: the text each kind of completion-report image is titled with,
#: ahead of what identifies it and its own caption
REPAIR_TITLES = {"false": "Itemized List of Repairs", "true": "New Observed Items for Repair"}
INCONSISTENT_TITLE = "Inconsistent Item"


def _kind_exhibits(ctx: Ctx, report: str) -> list[dict]:
    """An update / completion report's exhibits, titled as B-2 / B-3 compose
    them (B-3 p30-32): a repair's photo "Itemized List of Repairs - [Feature]
    - [caption]", a newly observed one "New Observed Items for Repair - ...",
    an item not completed per plans "Inconsistent Item - [Feature] -
    [caption]", any other "[category] - [caption]" -- the category's display
    text from A-2 / A-3, none for the ...Exhibit categories.  The subject's
    front photo and the legal description's image have boxes of their own."""
    from .. import report_types
    shown: dict[str, str] = {}
    for f in report_types.spec(report)["fields"].values():
        for dp in f["data_points"]:
            if dp.get("mismo") == "ImageCategoryType":
                for e in dp.get("enumerations") or []:
                    shown.setdefault(e["value"], e.get("display", ""))
    feature = binding(report_types.fid(report, "03.001"))
    out = []
    rank: list[int] = []
    for im in _images(ctx):
        if im["category"] in ("PropertyPhoto", "LegalDescription"):
            continue
        node = im["node"]
        owner = next((a for a in node.iterancestors()
                      if _local(a) in ("DEFECT", "SUBJECT_TO_COMPLETION_ITEM")), None)
        parts: list[str] = []
        if owner is not None and _local(owner) == "DEFECT":
            new = (_find_text(owner, "CompletionReportNewDefectIndicator") or "false").strip()
            parts.append(REPAIR_TITLES.get(new, REPAIR_TITLES["false"]))
            rank.append(1 if new == "true" else 0)
            group = [(n, _find_text(owner, n)) for n in
                     ("DefectComponentLabelType", "DefectComponentLabelTypeOtherDescription")
                     if _find_text(owner, n)]
            if group and feature is not None:
                parts.append(bind.display_value(group, feature))
        elif owner is not None:
            parts += [INCONSISTENT_TITLE, _find_text(owner, "SubjectToCompletionFeatureDescription")]
            rank.append(3)
        else:
            parts.append(shown.get(im["category"], ""))
            rank.append(2 if im["category"] == "CompletedConstruction" else 4)
        parts.append(im["caption"])
        title = " - ".join(p.strip() for p in parts if p and p.strip())
        out.append({"src": _data_uri(im["path"]), "title": title, "caption": "",
                    "location": im["location"], "category": im["category"],
                    "layout": layout_of(im["category"]), "media_id": "",
                    "image_key": bind.stable_path(node), "raw_caption": im["caption"]})
    # in the order B-3 ch. 07 lists them: repairs, newly observed items,
    # completed construction, inconsistent items, then any other exhibit
    order = sorted(range(len(out)), key=lambda n: (rank[n], n))
    return [out[n] for n in order]


