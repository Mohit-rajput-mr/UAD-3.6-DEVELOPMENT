@lru_cache(maxsize=1)
def _wingdings_css() -> str:
    path = fonts.source("Wingdings2")
    if path is None:
        return ""
    data = base64.b64encode(path.read_bytes()).decode("ascii")
    return ("@font-face{font-family:'UAD Wingdings2';"
            f"src:url(data:font/ttf;base64,{data}) format('truetype')}}")


def _screen_css() -> str:
    return """
body{background:#6f6f6f;padding:12px 0;overflow-x:hidden}
.page{margin:0 auto 12px;box-shadow:0 2px 10px rgba(0,0,0,.4)}
"""
