def _arc_linked(scope: etree._Element, xpath: str) -> etree._Element | None:
    """The block an arc ties to a scope, when the field lives there and not
    inside the scope: a dwelling's IMPROVEMENT_COST_AND_DEPRECIATED_VALUE is
    under COST_APPROACH, tied to the IMPROVEMENT by
    IMPROVEMENT_COST_AND_DEPRECIATED_VALUE_IsAssociatedWith_IMPROVEMENT."""
    label = scope.get(f"{XLINK}label")
    segs = [x for x in xpath.strip("/").split("/") if x]
    if not label or _local(scope) in segs:
        return None
    root = scope.getroottree().getroot()
    froms = {r.get(f"{XLINK}from") for r in root.iter(f"{M}RELATIONSHIP") if r.get(f"{XLINK}to") == label}
    if not froms:
        return None
    return next((e for e in root.iter() if isinstance(e.tag, str)
                 and e.get(f"{XLINK}label") in froms and _local(e) in segs), None)


def _walk(ctx: Ctx, fid: str, every: bool = False):
    b = binding(fid)
    if b is None:
        return
    if ctx.scope is not None and _local(ctx.scope) == "IMPROVEMENT" and b.data_points:
        linked = _arc_linked(ctx.scope, b.data_points[0].get("xpath", ""))
        if linked is not None:
            ctx = ctx.inside(linked)
    if fid == PRIOR_SOURCE_ID:
        # B-1 p284: with no prior sales, the Data Source tied to the subject's
        # PriorSalesOrTransfersIndicator ("None / Data Source MLS")
        subj = bind.subject(ctx.root)
        ind = _prior_indicator(subj) if subj is not None else None
        if ind is None or (ind.text or "").strip() != "false":
            return
        X = "{http://www.w3.org/1999/xlink}"
        label = ind.get(f"{X}label")
        froms = [r.get(f"{X}from") for r in ctx.root.iter(f"{M}RELATIONSHIP") if label and r.get(f"{X}to") == label]
        by = {d.get(f"{X}label"): d for d in ctx.root.iter(f"{M}DATA_SOURCE")}
        for f in dict.fromkeys(froms):
            ds = by.get(f)
            if ds is not None:
                yield from bind._walk(ctx.root, b, ds, 1)
        return
    if any("DATA_SOURCES/DATA_SOURCE" in dp.get("xpath", "") for dp in b.data_points):
        target = data_source_target(fid)
        if target and target != "PROPERTY":
            yield from _linked_sources(ctx, b, target)
            return
    category = commentary_category(fid)
    comment = any(dp.get("mismo") in ("ValuationCommentText", "ValueMarketabilityImpactType")
                  and "VALUATION_COMMENTAR" in dp.get("xpath", "") for dp in b.data_points)
    owner = "Owner" in b.label and any((dp.get("requires") or {}).get("PartyRoleType") == "PropertyOwner"
                                       for dp in b.data_points)
    if owner:
        names = {dp.get("mismo") for dp in b.data_points
                 if (dp.get("requires") or {}).get("PartyRoleType") == "PropertyOwner"}
        for party in ctx.root.iter(f"{M}PARTY"):
            roles = [(r.text or "").strip() for r in party.iter(f"{M}PartyRoleType")]
            if "PropertyOwner" not in roles:
                continue
            for node in party.iter():
                if isinstance(node.tag, str) and _local(node) in names and (node.text or "").strip():
                    yield _local(node), node
        return
    if ("-" in fid or every) and (ctx.scope is None or every):
        # An update / completion report's table column (C-3 Itemized List of
        # Repairs): one field ID for the column, one row per block.  A-1's
        # convention -- a field ID per repeat, the ordinal picking the block --
        # would read only the first repair.
        # a unit attribute is its element's (25.025 the area "@AreaUnitOf-
        # MeasureType"): the element is still read in every block
        points = [dp for dp in b.data_points if dp.get("mismo")
                  and (not dp.get("attribute") or dp["attribute"].endswith("UnitOfMeasureType"))
                  and "PARTIES/PARTY/" not in dp.get("xpath", "")]
        conts = {bind.repeating_container(dp.get("xpath", "")) for dp in points}
        subject_rows = ("Subject Property" in (_fields().get(fid, {}).get("roles") or [])
                        and bool(points) and all(bind.PROPERTY_PATH in dp.get("xpath", "") for dp in points))
        report_rows = bool(points) and not any(bind.PROPERTY_PATH in dp.get("xpath", "")
                                               or "DATA_SOURCES/" in dp.get("xpath", "") for dp in points)
        if every and "-" not in fid and ctx.scope is None and not subject_rows and not report_rows:
            # a table read for the whole report: only the subject's own blocks
            # are rows of it (a DATA_SOURCE or SALES_TRANSACTION outside the
            # subject belongs to a comparable or another section); the
            # report's own blocks (VALUATION_REVISION) are rows too
            conts = set()
        if len(conts) == 1 and "" not in conts:
            container = conts.pop()
            blocks, seen = [], set()
            base = ctx.scope if ctx.scope is not None else ctx.root
            if ctx.scope is None and subject_rows:
                # the subject's table: a comparable's site influences are its own
                base = bind.subject(ctx.root)
                if base is None:
                    return
            for dp in points:
                segs = bind._tail(dp.get("xpath", ""))
                for node in base.iter(f"{M}{dp['mismo']}"):
                    if segs and not bind._matches(node, segs):
                        continue
                    block = node.getparent()
                    while block is not None and _local(block) != container:
                        block = block.getparent()
                    if block is None:
                        continue
                    path = bind.stable_path(block)
                    if path not in seen:
                        seen.add(path)
                        blocks.append((path, block))
            if container == "IMAGE":
                # an image table takes only the categories A-1 names for its
                # category column (7.002.1: Floor Plan, Sketch) -- the RESNET
                # exhibit's caption is not a sketch's
                allowed = _image_categories(fid)
                if allowed:
                    blocks = [(p, blk) for p, blk in blocks
                              if (blk.findtext(f".//{M}ImageCategoryType") or "").strip() in allowed]
            order = {bind.stable_path(e): n for n, e in enumerate(ctx.root.iter(f"{M}{container}"))}
            for _path, block in sorted(blocks, key=lambda pb: order.get(pb[0], 0)):
                yield from bind._walk(ctx.root, b, block, 1)
            return
    roles = _fields().get(fid, {}).get("roles") or []
    if ctx.scope is None and roles and "Subject Property" not in roles and any(
            "PROPERTIES/PROPERTY" in dp.get("xpath", "") for dp in b.data_points):
        uses = {ROLE_USE.get(r, "") for r in roles}
        for prop in ctx.root.iter(f"{M}PROPERTY"):
            if prop.get("ValuationUseType") in uses:
                yield from bind._walk(ctx.root, b, prop, 1)
        return
    if repeats_as_list(fid):
        # One field, one value per repeated block (PROJECT_AMENITY each holds
        # one AmenityType): every block is read, not the first -- D-1 condo 2
        # prints all six of the project's amenities on this one row.
        principal = next(dp for dp in b.data_points if dp.get("mismo") == (printed_point(fid) or next(
            d["mismo"] for d in b.data_points if d.get("enumerations") and not d.get("attribute"))))
        container = bind.repeating_container(principal.get("xpath", ""))
        segs = bind._tail(principal.get("xpath", ""))
        base = ctx.scope if ctx.scope is not None else (
            bind.subject(ctx.root) if bind.PROPERTY_PATH in principal.get("xpath", "") else ctx.root)
        seen = set()
        needs = {k: v for k, v in (principal.get("requires") or {}).items() if not k.startswith(("@", "__"))}
        for node in (base.iter(f"{M}{principal['mismo']}") if base is not None else []):
            if not bind._matches(node, segs):
                continue
            if needs and not bind._instance_matches(node, needs):
                continue
            block = node.getparent()
            while block is not None and _local(block) != container:
                block = block.getparent()
            if block is None:
                continue
            path = bind.stable_path(block)
            if path in seen:
                continue
            seen.add(path)
            yield from bind._walk(ctx.root, b, block, 1)
        if seen:
            return
        # The field gathers data points from several kinds of block (Site
        # Influence Proximity 4.026: an ENVIRONMENTAL_CONDITION's, a
        # BODY_OF_WATER's, a SITE_INFLUENCE's) and the case holds none of the
        # principal's: the others are read as any field's are -- the 2-4
        # sample's "Busy Roadway | Bordering | Adverse" printed blank.
        # Every block of each other kind is read, so a second influence keeps
        # its own proximity.
        taken: list[etree._Element] = []
        single: list[dict] = []
        for dp in b.data_points:
            if dp is principal or not dp.get("mismo") or dp.get("attribute"):
                continue
            cont = bind.repeating_container(dp.get("xpath", ""))
            segs_ = bind._tail(dp.get("xpath", ""))
            if not cont:
                single.append(dp)
                continue
            for node in (base.iter(f"{M}{dp['mismo']}") if base is not None else []):
                if not bind._matches(node, segs_):
                    continue
                block = node.getparent()
                while block is not None and _local(block) != cont:
                    block = block.getparent()
                if block is None or any(block is t or t in block.iterancestors() or block in t.iterancestors()
                                        for t in taken):
                    continue
                taken.append(block)
                one = bind.Binding(b.field_id, b.section, b.subsection, b.label, [dp])
                yield from bind._walk(ctx.root, one, block, 1)
        if not taken and base is not None:
            # nothing in any repeated block: a point the property holds once
            # answers the row (PropertyMixedUsageIndicator in
            # PROPERTY_USE_SUMMARY -- D-1 SF1 "Non-Residential Use  None")
            for dp in single:
                one = bind.Binding(b.field_id, b.section, b.subsection, b.label, [dp])
                yield from bind._walk(ctx.root, one, base, 1)
        return
    for name, node in bind._walk(ctx.root, b, ctx.scope, 1):
        if comment and name in ("ValuationCommentText", "ValueMarketabilityImpactType"):
            if not category:
                continue
            got = node.getparent().findtext(f"{M}ValuationAnalysisCategoryType", "").strip()
            if got != category:
                continue
        yield name, node


def raw_values(ctx: Ctx, fid: str) -> list[str]:
    return [(n.text or "").strip() for _name, n in _walk(ctx, fid)
            if (n.text or "").strip()]


@lru_cache(maxsize=4096)
def _graph_categories(fid: str) -> "frozenset[str] | None":
    """Market "Graph" (17.017) is ImageCategoryType alone: B-1 lists the
    graphs ("the display text for each type is listed in the Market Exhibits
    subsection"), so only the categories filed under the field's own section
    print -- not every photo's category (D-1 SF1: Absorption Rate | Median
    Days on Market | Price Trend | Year Built of Sales)."""
    b = binding(fid)
    if b is None or [dp.get("mismo") for dp in b.data_points] != ["ImageCategoryType"] or not b.section:
        return None
    return frozenset(c for c, (sec, _cap) in image_categories().items() if sec == b.section)


def instances(ctx: Ctx, fid: str, every: bool = False) -> list[tuple[str, list[tuple[str, str]]]]:
    """Values grouped by the repeated container each sits in, in document order.
    ``every`` reads every block of the field's repeating container (a table
    whose rows are blocks: the defects), not the ordinal's one."""
    order: list[str] = []
    groups: dict[str, list[tuple[str, str]]] = {}
    # an update / completion report's row identity (report_types.entry)
    only = field_entry(fid).get("instance") if "-" in fid else None
    graphs = _graph_categories(fid)
    for name, node in _walk(ctx, fid, every):
        text = (node.text or "").strip()
        if not text:
            continue
        if graphs is not None and text not in graphs:
            continue
        if only and not bind._instance_matches(node, only):
            continue
        key = bind.instance_of(node)
        if key not in groups:
            groups[key] = []
            order.append(key)
        text = bind.with_unit(text, node)
        if (name, text) not in groups[key]:
            groups[key].append((name, text))
    return [(k, groups[k]) for k in order]


AREA_UNITS = {"SquareFeet": "Sq. Ft.", "Acres": "Acres", "SquareMeters": "Sq. M.",
              "Hectares": "Hectares"}


def _area(text: str, unit: str) -> str:
    """An area as the samples print it: '14,950 Sq. Ft.', '10.5 Acres'."""
    try:
        number = float(text)
    except ValueError:
        return f"{text} {AREA_UNITS.get(unit, unit)}"
    shown = f"{number:,.3f}".rstrip("0").rstrip(".")
    return f"{shown} {AREA_UNITS.get(unit, bind._humanise(unit))}"


def shown(ctx: Ctx, fid: str) -> list[str]:
    """The printed text for a field: one entry per instance it holds."""
    return [text for text, _key in shown_pairs(ctx, fid)]


def shown_pairs(ctx: Ctx, fid: str) -> list[tuple[str, str]]:
    """(printed text, stable address of the repeated block it sits in) per
    instance -- so the editor writes each value back into its own block."""
    b = binding(fid)
    if b is None:
        return []
    out = []
    per = "Per " in (b.label or "")
    tree = ctx.root.getroottree()
    groups = instances(ctx, fid)
    principal = printed_point(fid)
    paren = _bracketed_beside(fid)
    if fid in ALPHABETICAL and len(groups) > 1:
        groups = sorted(groups, key=lambda g: re.sub(r"[^a-z0-9]", "", bind.display_value(g[1], b).lower()))
    for key, group in groups:
        own = [p for p in group if p[0] == principal or p[0].endswith("OtherDescription")]
        rest = [p for p in group if p not in own]
        if paren and principal and rest and bind.display_value(rest, b):
            # B-1 18.012: the ownership "Display in () next to Amenity Type"
            main = bind.display_value(own, b)
            text = f"{main} ({bind.display_value(rest, b)})" if main else bind.display_value(rest, b)
        else:
            text = bind.display_value(group, b)
        if text and not per:
            text = re.sub(r"(\$[\d,]+)\.00\b", r"\1", text)
        if text and not ctx.edit:
            text = b1_value(fid, text)
        if text:
            stable = ""
            if key.startswith("/"):
                hit = tree.xpath(key)
                stable = bind.stable_path(hit[0]) if hit else ""
            out.append((text, stable))
    return out


