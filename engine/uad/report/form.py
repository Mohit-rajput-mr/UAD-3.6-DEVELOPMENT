def _fixed_text_answer(ctx: "Ctx", fid: str, printed: str) -> "Block | None":
    """The appraiser's own answer inside a section of fixed wording.

    Most of the Certifications is the report's own text, but a few of its
    slots are questions: "Have you performed services on this property in the
    prior three years?", the description that follows it, the date of
    signature.  Those are drawn with the label A-1 gives them so they can be
    answered, and print once they are.
    """
    b = binding(fid)
    if b is None or not b.data_points:
        return None
    if commentary_category(fid):
        return None                      # commentary has its own box already
    from .. import edit as _edit
    try:
        dp = _edit.choose_data_point(b)
    except (KeyError, ValueError):
        dp = (b.data_points or [{}])[0]
    kind_ = (dp.get("format_type") or "").strip().casefold()
    # A closed list or a Yes/No does not print an answer of its own: it
    # chooses which certification paragraph prints, and that paragraph is the
    # answer.  Free text and dates are the appraiser's own words and print.
    chooses = kind_ in ("enumerated", "boolean")
    value = text_of(ctx, [fid], " ")
    if not ctx.edit and (chooses or not value):
        return None
    label = b.label if b.label not in ("{No Label}", "") else b.subsection
    control = _value_control(ctx, fid, value) if ctx.edit else None
    if control is None:
        if ctx.edit:
            control = (f"<span class='v' data-fid='{esc(fid)}' contenteditable='true'"
                       f" spellcheck='true' data-ph='Answer'>{esc(value)}</span>")
        else:
            control = esc(value)
    return Block("text", section=printed, visible=True, fids=[fid],
                 html=(f"<div class='txc certans'><span class='cl'>{esc(label)}</span>"
                       f"{control}</div>"))


def _value_control(ctx: Ctx | None, fid: str, shown: str) -> str | None:
    """The control a value takes on the page, by what A-1 says it holds.

    C-1 sets some values on a line after a bold label and others straight
    under a bar, and the editor had drawn every one of those as a free-text box
    -- so "Does this appear to be an arm's length transaction?" took typing,
    and Lien Detail, which A-1 closes to four values, took anything at all.  A
    Yes/No is the pair of boxes the report prints; a closed list is the list;
    only what is genuinely free text is typed.  None means free text.
    """
    from .. import edit

    try:
        dp = edit.choose_data_point(edit.field(fid).binding)
    except (KeyError, ValueError):
        return None
    if (dp.get("format_type") or "").strip().casefold() == "boolean":
        if ctx is not None:
            state = checkbox(ctx, fid, "")
        else:
            # without the case to hand, the printed answer says which box
            answer = (shown or "").strip().casefold()
            state = True if answer in ("yes", "true") else False if answer in ("no", "false") else None
        return _boxes(state, fid)
    if choices_for(fid):
        return _picker(fid, shown)
    return None


def checkbox(ctx: Ctx, fid: str, label: str) -> bool | None:
    """True/False for a Yes/No box, or None when the case does not answer it."""
    values = raw_values(ctx, fid)
    if not values:
        return None
    b = binding(fid)
    first = values[0].strip().casefold()
    if first in ("true", "false"):
        return first == "true"
    # A label that is one of the field's own enumerations asks "is it this?"
    options: dict[str, str] = {}
    for dp in (b.data_points if b else []):
        for opt in dp.get("enumerations") or []:
            if opt.get("value"):
                options[opt["value"].casefold()] = (opt.get("display") or "").casefold()
    want = re.sub(r"\s*\(.*?\)\s*", "", label).strip().casefold()
    for v in values:
        vv = v.casefold()
        if vv == want or options.get(vv, "") == label.casefold() or \
                re.sub(r"[^a-z]", "", vv) == re.sub(r"[^a-z]", "", want):
            return True
    if first in ("yes", "no"):
        return first == "yes"
    return False


