"""Sort TOTAL's field-validation findings by cause, so none is "fixed" by guessing.

For each finding of a round trip (tools/roundtrip.py --photos output), the
field is traced to the MISMO data point(s) it holds (TOTAL's own table,
knowledge/total/builds/<build>/validation_profile.json) and the package is
checked for that value on that property:

  pipeline-defect   the package carries the value, TOTAL does not show it:
                    our import/placement lost it -> fix the mechanism
  data-gap          the package does not carry it: the case (or the official
                    sample) lacks the fact -> intake must supply it or ask
  adjustment-rule   an "adjustment entry is required when subject and
                    comparable data differ" row: TOTAL wants an explicit amount
                    (0 when the appraiser made none) -> generator convention
                    (CATALOG E-031); reported with whether the row's data is
                    itself complete on both sides
  untraced          no data point known for the field

    python tools/classify_findings.py --run ../knowledge/total/e2e/0.0.1.3848/total --build 0.0.1.3848
"""
from __future__ import annotations

import argparse
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

from lxml import etree

HERE = Path(__file__).resolve().parent
KNOW = HERE.parents[1] / "knowledge" / "total"
GRID = {"GC": "SalesComparable", "RP": "RentalComparable", "RC": "RentalComparable",
        "GR": "GrossRentMultiplierComparable"}


def _local(tag) -> str:
    return etree.QName(tag).localname if isinstance(tag, str) else ""


def properties(xml: Path, by_address: bool = False) -> dict:
    """(role, ordinal) -> set of data point names carrying a value; ordinal 0 =
    subject.  With by_address, keyed (role, street address) instead, and each
    comparable's (role, ordinal) -> address is under the key "addresses"."""
    root = etree.parse(str(xml), etree.XMLParser(huge_tree=True, recover=True)).getroot()
    out: dict = defaultdict(set)
    addresses = {}
    counters: Counter = Counter()
    for prop in root.iter("{*}PROPERTY"):
        role = prop.get("ValuationUseType") or ""
        counters[role] += 1
        ordinal = 0 if role == "SubjectProperty" else counters[role]
        street = re.sub(r"\s+", " ", (prop.findtext("{*}ADDRESS/{*}AddressLineText") or "").strip().upper())
        addresses[(role, ordinal)] = street
        key = (role, street if by_address and ordinal and street else ordinal)
        for e in prop.iter():
            if isinstance(e.tag, str) and len(e) == 0 and (e.text or "").strip():
                out[key].add(_local(e.tag))
    out["addresses"] = addresses
    return out


def base_of(field: str) -> tuple[str, str, int]:
    """'GC2_DP_FINTYP1_ADJ' -> ('DP_FINTYP1_ADJ', 'SalesComparable', 2)."""
    m = re.match(r"^(GC|GR|RP|RC)(\d+)(?:\.(\d+))?_(.+)$", field or "")
    if m:
        return m.group(4), GRID[m.group(1)], int(m.group(3) or m.group(2))
    return field or "", "SubjectProperty", 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--run", required=True, help="a roundtrip --photos output folder")
    ap.add_argument("--build", default="0.0.1.3848")
    a = ap.parse_args(argv)
    profile = json.loads((KNOW / "builds" / a.build / "validation_profile.json").read_text(encoding="utf-8"))
    dps_of = defaultdict(set)
    for rule in profile:
        for d in rule["data_points"]:
            dps_of[rule["field"]].add(d["data_point"])
    # TOTAL's MISMO table by base field name (covers fields whose finding is
    # raised by a custom validation rather than a registered validator)
    uid_map = json.loads((KNOW / "builds" / a.build / "uid_map.json").read_text(encoding="utf-8"))
    for dp, placements in uid_map.items():
        for x in placements:
            name = x["BaseDataFieldName"]
            dps_of[name].add(dp)
            if name.startswith("PU_"):
                dps_of[name[3:]].add(dp)
    run = Path(a.run)
    report = {}
    lines = ["# Field-validation findings by cause (generated by `tools/classify_findings.py`)", "",
             "| Sample | Findings | Pipeline defect | Data gap | Adjustment rule | Untraced |", "|---|---|---|---|---|---|"]
    detail = []
    for d in sorted(p for p in run.iterdir() if (p / "eando.json").exists()):
        eo = json.loads((d / "eando.json").read_text(encoding="utf-8"))
        state = json.loads((d / "state.json").read_text(encoding="utf-8"))
        pkg = Path(state["file"])
        if not pkg.exists():
            continue
        # what the package carries per property (by street address: TOTAL
        # renumbers columns), and what TOTAL's own XML kept (by TOTAL's column)
        pkg_props = properties(pkg, by_address=True)
        tot_props = properties(d / "total.xml") if (d / "total.xml").exists() else None

        def package_has(role, ordinal):
            if not ordinal:
                return pkg_props.get((role, 0), set())
            source = tot_props if tot_props is not None else pkg_props
            street = source["addresses"].get((role, ordinal), "")
            return pkg_props.get((role, street or ordinal), set())

        rows = []
        for f in eo.get("field_validation", []):
            base, role, ordinal = base_of(f.get("field"))
            msg = f.get("message") or ""
            have = package_has(role, ordinal)
            if base.endswith("_ADJ"):
                # an adjustment row: complete when the comparable carries the
                # row's own data (then only the amount convention is missing)
                dps = dps_of.get(base[:-4], set())
                kind = "adjustment-rule" if (not dps or dps & have) else "data-gap"
            else:
                dps = dps_of.get(base, set())
                if not dps:
                    kind = "untraced"
                elif tot_props is None:
                    kind = "pipeline-defect" if dps & have else "data-gap"
                else:
                    # ours only when TOTAL lost a value the package has; a field
                    # whose other half the package never carried is a data gap
                    lost = (dps & have) - tot_props.get((role, ordinal), set())
                    kind = "pipeline-defect" if lost else "data-gap"
            rows.append({"field": f.get("field"), "role": role, "ordinal": ordinal, "kind": kind,
                         "data_points": sorted(dps)[:4], "message": msg[:120]})
        c = Counter(r["kind"] for r in rows)
        report[d.name] = {"counts": dict(c), "rows": rows}
        lines.append(f"| {d.name} | {len(rows)} | {c.get('pipeline-defect', 0)} | {c.get('data-gap', 0)} | "
                     f"{c.get('adjustment-rule', 0)} | {c.get('untraced', 0)} |")
        for r in rows:
            if r["kind"] in ("pipeline-defect", "untraced"):
                detail.append(f"| {d.name} | {r['kind']} | {r['field']} | {', '.join(r['data_points'])} | {r['message']} |")
    lines += ["", "## Pipeline defects and untraced findings (each must be explained)", "",
              "| Sample | Kind | Field | Data points | Message |", "|---|---|---|---|---|"] + detail
    (run / "FINDINGS_BY_CAUSE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (run / "findings_by_cause.json").write_text(json.dumps(report, indent=1), encoding="utf-8")
    print("\n".join(lines[:20]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
