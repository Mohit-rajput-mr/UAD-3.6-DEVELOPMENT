"""What changed in WinTOTAL's UAD 3.6 form between two web-engine builds.

TOTAL updates itself; the Import Module's knowledge (knowledge/total/builds/)
is per build.  Before trusting the module on a new build, extract the new
build (tools/form_model.py) and run this: it lists the validators, fields,
pick-list items, MISMO placements, messages, repeatables and templates that
were added, removed or changed, and writes builds/<new>/DIFF_FROM_<old>.md.

    python tools/diff_builds.py 0.0.1.3848 0.0.1.3855
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

BUILDS = Path(__file__).resolve().parents[2] / "knowledge" / "total" / "builds"


def _load(build: str, name: str):
    p = BUILDS / build / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _validators(v):
    return {(x["field"], x["trigger"], tuple(x["rule_names"]), x["validator_class"]) for x in v or []}


def _fields(f):
    # popups carry a per-report GUID: compare them as "popup", not by id
    return {(x["field"], x["control"], x["fmid"], x["section"] or x["template"] or ("popup" if x["popup"] else ""))
            for x in f or []}


def _placements(m):
    return {(dp, x.get("BaseDataFieldName"), x.get("FieldPrefix", ""), x.get("UID"), x.get("FMID"))
            for dp, rows in (m or {}).items() for x in rows}


def _messages(m):
    out = set()
    for sect, fields in (m or {}).items():
        if isinstance(fields, dict):
            for field, rules in fields.items():
                if isinstance(rules, dict):
                    for rule, text in rules.items():
                        out.add((sect, field, rule, text))
    return out


def _items(df):
    return {(name, tuple(v.get("items") or [])) for name, v in (df or {}).items()}


def _classes(bp):
    """Every class of TOTAL's code with its size: a class whose size changed is
    code that changed, even when no field, validator or message did."""
    out = {}
    for m in (bp or {}).get("modules", []):
        for c in m["classes"]:
            out.setdefault(c["class"], []).append(c["chars"])
    return {(k, tuple(sorted(v))) for k, v in out.items()}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("old")
    ap.add_argument("new")
    a = ap.parse_args(argv)
    checks = [
        ("validators", "validators.json", _validators),
        ("controls", "fields.json", _fields),
        ("MISMO placements", "uid_map.json", _placements),
        ("validation messages", "rtv_messages.json", _messages),
        ("pick lists", "datafields.json", _items),
        ("repeatables", "repeatables.json", lambda r: {(x.get("key"), x.get("min"), x.get("max")) for x in r or []}),
        ("templates", "templates.json", lambda t: {(x["key"], len(x["fields"])) for x in t or []}),
        ("WinTOTAL actions", "connector.json",
         lambda c: set((c or {}).get("report_actions_from_wintotal", []))),
        # needs tools/blueprint.py run for both builds; read the changed
        # classes in the two bundle snapshots to learn what changed in them
        ("code (class sizes, from blueprint.json)", "blueprint.json", _classes),
    ]
    lines = [f"# WinTOTAL form changes: {a.old} → {a.new}", "",
             "Generated by `total-bridge/tools/diff_builds.py`. Each removed/added row is a set difference of "
             "the extracted tables; a changed item shows up once as removed and once as added.", ""]
    total = 0
    for title, name, key in checks:
        old, new = key(_load(a.old, name)), key(_load(a.new, name))
        gone, came = sorted(old - new, key=str), sorted(new - old, key=str)
        total += len(gone) + len(came)
        lines += [f"## {title}: {len(gone)} removed, {len(came)} added", ""]
        for row in gone[:80]:
            lines.append(f"- removed `{row}`")
        for row in came[:80]:
            lines.append(f"- added `{row}`")
        if len(gone) > 80 or len(came) > 80:
            lines.append("- … (truncated)")
        lines.append("")
    out = BUILDS / a.new / f"DIFF_FROM_{a.old}.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:200]))
    print(f"\n{total} differences -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
